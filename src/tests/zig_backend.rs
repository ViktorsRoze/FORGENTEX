use std::fs;

use crate::zig_backend::{build_zig_project, generate_zig_for_project};

use super::manifest_path;

#[test]
fn zig_backend_generates_source_for_media_project() {
    let source = generate_zig_for_project(&manifest_path(".")).unwrap();

    assert!(source.contains("// Generated by fgx build --backend zig."));
    assert!(source.contains("// FIR signatures: forgentex.backend_ir.v1"));
    assert!(source.contains("// FIR struct @struct.AudioBlock"));
    assert!(source.contains("// FIR body entry"));
    assert!(source.contains("fn fgx_bounds_index(index: usize, len: usize) usize"));
    assert!(source.contains("pub const AudioBlock = struct"));
    assert!(source.contains("pub fn mix_samples(dst: []i16"));
    assert!(source.contains("core_slice_require_mut_same_len_i16(dst, a);"));
    assert!(source.contains("if (!((dst.len == src.len))) fgx_trap(\"require_failed\")"));
    assert!(source.contains("dst[fgx_bounds_index(i, dst.len)] = core_math_clamp_i16(x);"));
    assert!(source.contains("return H264NalHeader{ .forbidden_zero = forbidden_zero"));
}

#[test]
fn zig_backend_writes_artifacts() {
    let out_dir =
        std::env::temp_dir().join(format!("forgentex_{}_zig_backend", std::process::id()));
    let _ = fs::remove_dir_all(&out_dir);
    let artifacts = build_zig_project(&manifest_path("."), &out_dir).unwrap();

    let source = fs::read_to_string(&artifacts.source).unwrap();
    assert!(artifacts.source.ends_with("forgentex_demo_media.zig"));
    assert!(source.contains("// FIR signatures: forgentex.backend_ir.v1"));
    assert!(source.contains("// FIR struct @struct.AudioBlock"));
    assert!(source.contains("// FIR body entry"));
    assert!(source.contains("pub fn mix_samples"));

    let _ = fs::remove_dir_all(out_dir);
}

#[test]
fn zig_backend_lowers_control_flow_from_fir() {
    let root = std::env::temp_dir().join(format!(
        "forgentex_{}_zig_backend_fir_cf",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(root.join("src")).unwrap();
    fs::write(
        root.join("Forgentex.toml"),
        "[package]\nname = \"fir-cf-zig\"\nversion = \"0.1.0\"\nroot = \"src\"\n",
    )
    .unwrap();
    fs::write(
        root.join("src/control.fgx"),
        "module fir.cf.zig\nexport fn branch_loop(n: usize) -> usize:\n    let total: usize = 0\n    for i in 0 .. n:\n        if i > 2:\n            continue\n        total = total + i\n    return total\n",
    )
    .unwrap();

    let source = generate_zig_for_project(&root).unwrap();
    assert!(source.contains("// FIR body entry"), "{source}");
    assert!(source.contains("var i: usize = 0;"), "{source}");
    assert!(source.contains("while (i < n) : (i += 1)"), "{source}");
    assert!(source.contains("if ((i > 2))"), "{source}");
    assert!(source.contains("continue;"), "{source}");

    let _ = fs::remove_dir_all(root);
}

#[test]
fn zig_backend_lowers_match_from_fir() {
    let root = std::env::temp_dir().join(format!(
        "forgentex_{}_zig_backend_fir_match",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(root.join("src")).unwrap();
    fs::write(
        root.join("Forgentex.toml"),
        "[package]\nname = \"fir-match-zig\"\nversion = \"0.1.0\"\nroot = \"src\"\n",
    )
    .unwrap();
    fs::write(
        root.join("src/match.fgx"),
        "module fir.match.zig\n\nenum Shape:\n    Circle(i32)\n    Empty\n\nexport fn area(shape: Shape) -> i32:\n    match shape:\n        case Shape::Circle(r):\n            return r * r\n        case Shape::Empty:\n            return 0\n\nexport fn circle_area() -> i32:\n    return area(Shape::Circle(3))\n",
    )
    .unwrap();

    let source = generate_zig_for_project(&root).unwrap();
    assert!(source.contains("// FIR enum @enum.Shape"), "{source}");
    assert!(source.contains("const Shape = union(enum)"), "{source}");
    assert!(source.contains("Circle: i32"), "{source}");
    assert!(source.contains("switch (shape)"), "{source}");
    assert!(source.contains(".Circle => |r| {"), "{source}");
    assert!(source.contains(".Empty => {"), "{source}");
    assert!(source.contains("Shape{ .Circle = 3 }"), "{source}");

    let _ = fs::remove_dir_all(root);
}

#[test]
fn zig_backend_rejects_review_only_assembly() {
    let root = std::env::temp_dir().join(format!(
        "forgentex_{}_zig_backend_unsafe",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(root.join("src")).unwrap();
    fs::write(
        root.join("Forgentex.toml"),
        "[package]\nname = \"unsafe-demo\"\nversion = \"0.1.0\"\nroot = \"src\"\n",
    )
    .unwrap();
    fs::write(
        root.join("src/pop.fgx"),
        "module unsafe.demo\nexport unsafe fn popcount_x86(x: u32) -> u32 effects [cpu.asm]:\n    asm x86_64:\n        in eax: x\n        out eax: x\n        clobber flags\n        op popcnt eax eax\n    return x\n",
    )
    .unwrap();

    let err = generate_zig_for_project(&root).unwrap_err();
    // The FIR contract preflight now rejects before source emission — same
    // honesty, one uniform gate for every build entry point.
    assert!(
        err.contains("FIR contract blocks backend") && err.contains("popcount_x86"),
        "expected a contract blocker naming the function, got: {err}"
    );

    let _ = fs::remove_dir_all(root);
}
