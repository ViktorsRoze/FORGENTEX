#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ZigBuildArtifacts {
    pub source: PathBuf,
}

pub fn build_zig_project(input: &Path, out_dir: &Path) -> Result<ZigBuildArtifacts, String> {
    let (artifacts, _ir, _report) = build_zig_project_inner(input, out_dir, false)?;
    Ok(artifacts)
}

/// `fgx build --opt`: optimize the loaded project (v3.2) before lowering and
/// emission — see `build_c_project_opt` for the shape.
pub fn build_zig_project_opt(
    input: &Path,
    out_dir: &Path,
) -> Result<(ZigBuildArtifacts, BackendIr, crate::optimize::OptReport), String> {
    let (artifacts, ir, report) = build_zig_project_inner(input, out_dir, true)?;
    Ok((artifacts, ir, report.unwrap_or_default()))
}

fn build_zig_project_inner(
    input: &Path,
    out_dir: &Path,
    optimize: bool,
) -> Result<
    (
        ZigBuildArtifacts,
        BackendIr,
        Option<crate::optimize::OptReport>,
    ),
    String,
> {
    let diagnostics = check_project(input)?;
    if !diagnostics.is_empty() {
        return Err(format!(
            "project has diagnostics and was not lowered:\n{}",
            diagnostics_to_json(&diagnostics)
        ));
    }
    let mut project = load_project(input)?;
    crate::monomorphize::monomorphize_project(&mut project)?;
    crate::closure_lower::lower_non_capturing_closures(&mut project);
    let report = optimize.then(|| crate::optimize::optimize_project(&mut project));
    let ir = crate::backend::generate_ready_backend_ir_from_project(&project, "zig")?;
    let package = package_ident(&project.manifest.name);
    let source_name = format!("{package}.zig");
    let source = generate_source(&project, &ir)?;

    fs::create_dir_all(out_dir)
        .map_err(|err| format!("failed to create {}: {err}", out_dir.display()))?;
    let source_path = out_dir.join(&source_name);
    fs::write(&source_path, source)
        .map_err(|err| format!("failed to write {}: {err}", source_path.display()))?;
    Ok((
        ZigBuildArtifacts {
            source: source_path,
        },
        ir,
        report,
    ))
}

pub fn generate_zig_for_project(input: &Path) -> Result<String, String> {
    let diagnostics = check_project(input)?;
    if !diagnostics.is_empty() {
        return Err(format!(
            "project has diagnostics and was not lowered:\n{}",
            diagnostics_to_json(&diagnostics)
        ));
    }
    let mut project = load_project(input)?;
    crate::monomorphize::monomorphize_project(&mut project)?;
    crate::closure_lower::lower_non_capturing_closures(&mut project);
    let ir = crate::backend::generate_ready_backend_ir_from_project(&project, "zig")?;
    generate_source(&project, &ir)
}

fn generate_source(project: &Project, ir: &BackendIr) -> Result<String, String> {
    let program = combined_program(project);
    let structs = program
        .structs()
        .map(|decl| (decl.name.clone(), decl.clone()))
        .collect::<HashMap<_, _>>();
    let enums = ir
        .modules
        .iter()
        .flat_map(|module| module.enums.iter())
        .map(|decl| (decl.name.clone(), decl.clone()))
        .collect::<HashMap<_, _>>();
    let function_returns = program
        .functions()
        .map(|decl| (decl.name.clone(), decl.ret.clone()))
        .collect::<HashMap<_, _>>();
    let mut out = String::new();
    out.push_str("// Generated by fgx build --backend zig.\n");
    out.push_str(&fir_signature_comment(ir));
    out.push_str("// Zig compiler invocation and build.zig generation are deferred.\n\n");
    out.push_str("const std = @import(\"std\");\n");
    out.push_str("const FGX_STR_MAX_BYTES: usize = 16 * 1024 * 1024;\n\n");
    out.push_str("fn fgx_trap(code: []const u8) noreturn {\n");
    out.push_str("    @panic(code);\n");
    out.push_str("}\n\n");
    out.push_str("fn fgx_bounds_index(index: usize, len: usize) usize {\n");
    out.push_str("    if (index >= len) fgx_trap(\"index_out_of_bounds\");\n");
    out.push_str("    return index;\n");
    out.push_str("}\n\n");
    out.push_str("fn fgx_str_len(value: []const u8) usize {\n");
    out.push_str("    if (value.len >= FGX_STR_MAX_BYTES) fgx_trap(\"string_too_large\");\n");
    out.push_str("    return value.len;\n");
    out.push_str("}\n\n");
    out.push_str("fn fgx_str_eq(left: []const u8, right: []const u8) bool {\n");
    out.push_str("    _ = fgx_str_len(left);\n");
    out.push_str("    _ = fgx_str_len(right);\n");
    out.push_str("    return std.mem.eql(u8, left, right);\n");
    out.push_str("}\n\n");
    out.push_str("fn fgx_str_contains(text: []const u8, needle: []const u8) bool {\n");
    out.push_str("    _ = fgx_str_len(text);\n");
    out.push_str("    _ = fgx_str_len(needle);\n");
    out.push_str("    return std.mem.indexOf(u8, text, needle) != null;\n");
    out.push_str("}\n\n");
    for (suffix, title, element) in [
        ("bool", "Bool", "bool"),
        ("i8", "I8", "i8"),
        ("i16", "I16", "i16"),
        ("i32", "I32", "i32"),
        ("i64", "I64", "i64"),
        ("isize", "Isize", "isize"),
        ("u8", "U8", "u8"),
        ("u16", "U16", "u16"),
        ("u32", "U32", "u32"),
        ("u64", "U64", "u64"),
        ("usize", "Usize", "usize"),
        ("f32", "F32", "f32"),
        ("f64", "F64", "f64"),
        ("str", "Str", "[]const u8"),
        ("slice_bool", "SliceBool", "[]const bool"),
        ("slice_i8", "SliceI8", "[]const i8"),
        ("slice_i16", "SliceI16", "[]const i16"),
        ("slice_i32", "SliceI32", "[]const i32"),
        ("slice_i64", "SliceI64", "[]const i64"),
        ("slice_isize", "SliceIsize", "[]const isize"),
        ("slice_u8", "SliceU8", "[]const u8"),
        ("slice_u16", "SliceU16", "[]const u16"),
        ("slice_u32", "SliceU32", "[]const u32"),
        ("slice_u64", "SliceU64", "[]const u64"),
        ("slice_usize", "SliceUsize", "[]const usize"),
        ("slice_f32", "SliceF32", "[]const f32"),
        ("slice_f64", "SliceF64", "[]const f64"),
    ] {
        out.push_str(&emit_named_native_vec_decl(suffix, title, element));
    }

    for (suffix, element) in native_vec_array_layouts(&program) {
        let title = native_vec_array_title(&element)
            .ok_or_else(|| "Zig backend received an unsupported native Vec array".to_string())?;
        out.push_str(&emit_named_native_vec_decl(
            &suffix,
            &title,
            &zig_type(&element)?,
        ));
    }

    for decl in program.enums() {
        out.push_str(&emit_enum_decl_from_ir(ir_enum_for_ast(ir, decl)?)?);
        out.push('\n');
    }

    for decl in program.enums() {
        let suffix = ident(&decl.name);
        let title = ident(&decl.name);
        let element = ident(&decl.name);
        out.push_str(&emit_named_native_vec_decl(&suffix, &title, &element));
    }

    for decl in program.structs() {
        out.push_str(&emit_struct_decl_from_ir(ir_struct_for_ast(ir, decl)?)?);
        out.push('\n');
    }

    for decl in program.structs() {
        let suffix = ident(&decl.name);
        out.push_str(&emit_named_native_vec_decl(&suffix, &suffix, &suffix));
    }

    for function in program.functions() {
        out.push_str(&emit_function(
            function,
            &structs,
            &enums,
            &function_returns,
            ir,
        )?);
        out.push('\n');
    }
    Ok(out)
}

fn emit_named_native_vec_decl(suffix: &str, title: &str, element: &str) -> String {
    let upper = suffix.to_ascii_uppercase();
    format!(
        "const FGX_VEC_{upper}_MAX_ELEMENTS: usize = 1024 * 1024;\n\
const FgxVec{title} = struct {{ data: ?[]{element} = null, len: usize = 0 }};\n\n\
fn fgx_vec_{suffix}_new() FgxVec{title} {{\n\
    return .{{}};\n\
}}\n\n\
fn fgx_vec_{suffix}_free(vec: *FgxVec{title}) void {{\n\
    if (vec.data) |buffer| std.heap.page_allocator.free(buffer);\n\
    vec.* = .{{}};\n\
}}\n\n\
fn fgx_vec_{suffix}_reserve_for_push(vec: *FgxVec{title}) void {{\n\
    if (vec.len >= FGX_VEC_{upper}_MAX_ELEMENTS) fgx_trap(\"vec_capacity_exceeded\");\n\
    if (vec.data) |buffer| {{\n\
        if (vec.len < buffer.len) return;\n\
    }}\n\
    const current: usize = if (vec.data) |buffer| buffer.len else 0;\n\
    const next: usize = @min(if (current == 0) 4 else current * 2, FGX_VEC_{upper}_MAX_ELEMENTS);\n\
    const fresh = std.heap.page_allocator.alloc({element}, next) catch fgx_trap(\"allocation_failed\");\n\
    if (vec.data) |old| {{\n\
        @memcpy(fresh[0..vec.len], old[0..vec.len]);\n\
        std.heap.page_allocator.free(old);\n\
    }}\n\
    vec.data = fresh;\n\
}}\n\n\
fn fgx_vec_{suffix}_push(vec: *FgxVec{title}, value: {element}) void {{\n\
    fgx_vec_{suffix}_reserve_for_push(vec);\n\
    vec.data.?[vec.len] = value;\n\
    vec.len += 1;\n\
}}\n\n\
fn fgx_vec_{suffix}_pop(vec: *FgxVec{title}) void {{\n\
    if (vec.len != 0) vec.len -= 1;\n\
}}\n\n\
fn fgx_vec_{suffix}_pop_value(vec: *FgxVec{title}) ?{element} {{\n\
    if (vec.len == 0) return null;\n\
    vec.len -= 1;\n\
    return vec.data.?[vec.len];\n\
}}\n\n"
    )
}

fn emit_enum_decl_from_ir(decl: &IrEnum) -> Result<String, String> {
    let visibility = if decl.public { "pub " } else { "" };
    let mut out = String::new();
    out.push_str(&format!("// FIR enum {}\n", decl.id));
    if enum_is_tagged_union_ir(decl) {
        out.push_str(&format!(
            "{visibility}const {} = union(enum) {{\n",
            ident(&decl.name)
        ));
        for variant in &decl.variants {
            match &variant.payload {
                Some(ty) => out.push_str(&format!(
                    "    {}: {},\n",
                    ident(&variant.name),
                    zig_type_from_ir(ty)?
                )),
                None => out.push_str(&format!("    {},\n", ident(&variant.name))),
            }
        }
    } else {
        out.push_str(&format!(
            "{visibility}const {} = enum {{\n",
            ident(&decl.name)
        ));
        for variant in &decl.variants {
            out.push_str(&format!("    {},\n", ident(&variant.name)));
        }
    }
    out.push_str("};\n");
    Ok(out)
}

fn emit_struct_decl_from_ir(decl: &IrStruct) -> Result<String, String> {
    let visibility = if decl.public { "pub " } else { "" };
    let mut out = String::new();
    out.push_str(&format!("// FIR struct {}\n", decl.id));
    out.push_str(&format!(
        "{visibility}const {} = struct {{\n",
        ident(&decl.name)
    ));
    for field in &decl.fields {
        out.push_str(&format!(
            "    {}: {},\n",
            ident(&field.name),
            zig_type_from_ir(&field.ty)?
        ));
    }
    out.push_str("};\n");
    Ok(out)
}

fn emit_function(
    function: &FunctionDecl,
    structs: &HashMap<String, StructDecl>,
    enums: &HashMap<String, IrEnum>,
    function_returns: &HashMap<String, Type>,
    ir: &BackendIr,
) -> Result<String, String> {
    ensure_zig_lowerable(function)?;
    let mut env = Env::from_params(&function.params, &function.ret, enums, function_returns);
    let ir_function = ir_function_for_ast(ir, function)?;
    let mut out = String::new();
    out.push_str(&function_signature_from_ir(ir_function)?);
    out.push_str(" {\n");
    try_emit_fir_body(ir_function, &mut env, structs, &mut out).map_err(|reason| {
        format!(
            "Zig backend could not emit FIR body for function '{}': {reason}",
            function.name
        )
    })?;
    out.push_str("}\n");
    Ok(out)
}

fn try_emit_fir_body(
    function: &IrFunction,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<(), String> {
    let Some(block) = function.blocks.iter().find(|block| block.label == "entry") else {
        return Err("missing entry block".to_string());
    };

    let mut trial_env = env.clone();
    let mut body = String::new();
    body.push_str("    // FIR body entry\n");
    let mut cursor = 0;
    match emit_fir_instructions(
        &block.instructions,
        &mut cursor,
        1,
        &mut trial_env,
        structs,
        &mut body,
        &[],
    )? {
        FirCursorStop::End => {}
        FirCursorStop::Terminator(op) => {
            return Err(format!("unexpected top-level FIR terminator '{op}'"));
        }
        FirCursorStop::Unsupported(reason) => return Err(reason),
    }
    if function.ret == "void" && !block.instructions.iter().any(|inst| inst.op == "return") {
        body.push_str("    return;\n");
    }
    *env = trial_env;
    out.push_str(&body);
    Ok(())
}

#[derive(Debug, PartialEq, Eq)]
enum FirCursorStop {
    End,
    Terminator(String),
    Unsupported(String),
}

fn emit_fir_instructions(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
    terminators: &[&str],
) -> Result<FirCursorStop, String> {
    while *cursor < instructions.len() {
        let op = instructions[*cursor].op.as_str();
        if terminators.contains(&op) {
            return Ok(FirCursorStop::Terminator(op.to_string()));
        }
        let emitted = match op {
            "if" => emit_fir_if(instructions, cursor, level, env, structs, out)?,
            "for" => emit_fir_for(instructions, cursor, level, env, structs, out)?,
            "while" => emit_fir_while(instructions, cursor, level, env, structs, out)?,
            "match" => emit_fir_match(instructions, cursor, level, env, structs, out)?,
            "let" | "return" | "require" | "assign" | "expr" | "break" | "continue" => {
                let emitted =
                    emit_fir_instruction(&instructions[*cursor], level, env, structs, out)?;
                if emitted {
                    *cursor += 1;
                }
                emitted
            }
            _ => false,
        };
        if !emitted {
            return Ok(FirCursorStop::Unsupported(format!(
                "unsupported or malformed FIR op '{}' at instruction {}",
                instructions[*cursor].op, *cursor
            )));
        }
    }
    Ok(FirCursorStop::End)
}

fn emit_fir_if(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [cond_text, _then_len] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let cond = match parse_expr(cond_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let pad = indent(level);
    out.push_str(&format!(
        "{pad}if ({}) {{\n",
        emit_expr(&cond, env, structs)?
    ));
    *cursor += 1;

    let mut then_env = env.clone();
    match emit_fir_instructions(
        instructions,
        cursor,
        level + 1,
        &mut then_env,
        structs,
        out,
        &["else", "endif"],
    )? {
        FirCursorStop::Terminator(op) if op == "else" => {
            *cursor += 1;
            out.push_str(&format!("{pad}}} else {{\n"));
            let mut else_env = env.clone();
            match emit_fir_instructions(
                instructions,
                cursor,
                level + 1,
                &mut else_env,
                structs,
                out,
                &["endif"],
            )? {
                FirCursorStop::Terminator(op) if op == "endif" => {
                    *cursor += 1;
                    out.push_str(&format!("{pad}}}\n"));
                    Ok(true)
                }
                _ => Ok(false),
            }
        }
        FirCursorStop::Terminator(op) if op == "endif" => {
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn emit_fir_for(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [var, start_text, end_text, _body_len] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let start = match parse_expr(start_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let end = match parse_expr(end_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let start = emit_expr(&start, env, structs)?;
    let end = emit_expr(&end, env, structs)?;
    let pad = indent(level);
    out.push_str(&format!("{pad}var {}: usize = {start};\n", ident(var)));
    out.push_str(&format!(
        "{pad}while ({} < {end}) : ({} += 1) {{\n",
        ident(var),
        ident(var)
    ));
    *cursor += 1;
    let mut loop_env = env.clone();
    loop_env.insert(var, Type::Primitive("usize".to_string()));
    match emit_fir_instructions(
        instructions,
        cursor,
        level + 1,
        &mut loop_env,
        structs,
        out,
        &["endfor"],
    )? {
        FirCursorStop::Terminator(op) if op == "endfor" => {
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn emit_fir_while(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [cond_text, _body_len] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let cond = match parse_expr(cond_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let pad = indent(level);
    out.push_str(&format!(
        "{pad}while ({}) {{\n",
        emit_expr(&cond, env, structs)?
    ));
    *cursor += 1;
    let mut loop_env = env.clone();
    match emit_fir_instructions(
        instructions,
        cursor,
        level + 1,
        &mut loop_env,
        structs,
        out,
        &["endwhile"],
    )? {
        FirCursorStop::Terminator(op) if op == "endwhile" => {
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn emit_fir_match(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [scrutinee_text, _arms] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let scrutinee = match parse_expr(scrutinee_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let scrutinee_text = emit_expr(&scrutinee, env, structs)?;
    let pad = indent(level);
    let case_pad = indent(level + 1);
    out.push_str(&format!("{pad}switch ({scrutinee_text}) {{\n"));
    *cursor += 1;

    loop {
        let Some(case) = instructions.get(*cursor) else {
            return Ok(false);
        };
        if case.op == "endmatch" {
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            return Ok(true);
        }
        if case.op != "case" {
            return Ok(false);
        }
        let [pattern_text] = case.args.as_slice() else {
            return Ok(false);
        };
        let Some(pattern) = parse_fir_pattern(pattern_text) else {
            return Ok(false);
        };

        let mut arm_env = env.clone();
        match &pattern {
            Pattern::Wildcard => out.push_str(&format!("{case_pad}else => {{\n")),
            Pattern::Variant { path, binding } => {
                let variant = path.rsplit("::").next().unwrap_or("");
                if let Some(binding) = binding {
                    let enum_name = path.split("::").next().unwrap_or("");
                    if let Some(payload) = env.variant_payload(enum_name, variant) {
                        arm_env.insert(binding, payload);
                    }
                    out.push_str(&format!(
                        "{case_pad}.{} => |{}| {{\n",
                        ident(variant),
                        ident(binding)
                    ));
                } else {
                    out.push_str(&format!("{case_pad}.{} => {{\n", ident(variant)));
                }
            }
        }

        *cursor += 1;
        match emit_fir_instructions(
            instructions,
            cursor,
            level + 2,
            &mut arm_env,
            structs,
            out,
            &["case", "endmatch"],
        )? {
            FirCursorStop::Terminator(op) if op == "case" || op == "endmatch" => {
                out.push_str(&format!("{case_pad}}},\n"));
                if op == "endmatch" {
                    *cursor += 1;
                    out.push_str(&format!("{pad}}}\n"));
                    return Ok(true);
                }
            }
            _ => return Ok(false),
        }
    }
}

fn parse_fir_pattern(text: &str) -> Option<Pattern> {
    let text = text.trim();
    if text == "_" {
        return Some(Pattern::Wildcard);
    }
    let (path, binding) = if let Some(open) = text.find('(') {
        let path = text[..open].trim().to_string();
        let name = text[open + 1..].strip_suffix(')')?.trim().to_string();
        (path, Some(name))
    } else {
        (text.to_string(), None)
    };
    if !path.contains("::") {
        return None;
    }
    Some(Pattern::Variant { path, binding })
}

fn emit_fir_instruction(
    instruction: &IrInstruction,
    level: usize,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let pad = indent(level);
    match instruction.op.as_str() {
        "let" => {
            let [name, expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            let ty = instruction
                .ty
                .as_deref()
                .map(Type::parse)
                .unwrap_or_else(|| inferred_zig_type(&expr, env, structs));
            let value = match (&expr, native_vec_suffix(&ty), native_option_suffix(&ty)) {
                (Expr::Call { .. }, _, Some(_)) if is_native_option_constructor(&expr) => {
                    emit_native_option_constructor(&expr, env, structs)?
                }
                (Expr::Call { name, args }, _, Some(suffix))
                    if name == "pop" && args.len() == 1 =>
                {
                    format!(
                        "fgx_vec_{suffix}_pop_value(&{})",
                        emit_expr(&args[0], env, structs)?
                    )
                }
                (Expr::Call { name, args }, Some(suffix), _)
                    if name == "vec_new" && args.is_empty() =>
                {
                    format!("fgx_vec_{suffix}_new()")
                }
                _ => emit_expr(&expr, env, structs)?,
            };
            out.push_str(&format!(
                "{pad}var {}: {} = {value};\n",
                ident(name),
                zig_type(&ty)?
            ));
            if let Some(suffix) = native_vec_suffix(&ty) {
                out.push_str(&format!(
                    "{pad}defer fgx_vec_{suffix}_free(&{});\n",
                    ident(name)
                ));
            }
            env.insert(name, ty);
        }
        "return" => match instruction.args.as_slice() {
            [] => out.push_str(&format!("{pad}return;\n")),
            [expr_text] => {
                let expr = match parse_expr(expr_text) {
                    Ok(expr) => expr,
                    Err(_) => return Ok(false),
                };
                let value = match (&expr, native_option_suffix(&env.return_type)) {
                    (Expr::Call { .. }, Some(_)) if is_native_option_constructor(&expr) => {
                        emit_native_option_constructor(&expr, env, structs)?
                    }
                    (Expr::Call { name, args }, Some(suffix))
                        if name == "pop" && args.len() == 1 =>
                    {
                        format!(
                            "fgx_vec_{suffix}_pop_value(&{})",
                            emit_expr(&args[0], env, structs)?
                        )
                    }
                    _ => emit_expr(&expr, env, structs)?,
                };
                out.push_str(&format!("{pad}return {value};\n"));
            }
            _ => return Ok(false),
        },
        "require" => {
            let [expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            out.push_str(&format!(
                "{pad}if (!({})) fgx_trap(\"require_failed\");\n",
                emit_expr(&expr, env, structs)?
            ));
        }
        "assign" => {
            let [target_text, expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let target = match parse_expr(target_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            emit_assignment(&target, &expr, level, env, structs, out)?;
        }
        "expr" => {
            let [expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            out.push_str(&format!("{pad}{};\n", emit_expr(&expr, env, structs)?));
        }
        "break" => out.push_str(&format!("{pad}break;\n")),
        "continue" => out.push_str(&format!("{pad}continue;\n")),
        _ => return Ok(false),
    }
    Ok(true)
}

fn emit_assignment(
    target: &Expr,
    expr: &Expr,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<(), String> {
    let pad = indent(level);
    let value = emit_expr(expr, env, structs)?;
    match target {
        Expr::Index { base, index } => {
            let base_text = emit_expr(base, env, structs)?;
            let index_text = emit_expr(index, env, structs)?;
            if is_native_vec(&inferred_zig_type(base, env, structs)) {
                out.push_str(&format!(
                    "{pad}{base_text}.data.?[fgx_bounds_index({index_text}, {base_text}.len)] = {value};\n"
                ));
            } else {
                out.push_str(&format!(
                    "{pad}{base_text}[fgx_bounds_index({index_text}, {base_text}.len)] = {value};\n"
                ));
            }
        }
        _ => out.push_str(&format!(
            "{pad}{} = {value};\n",
            emit_expr(target, env, structs)?
        )),
    }
    Ok(())
}

fn emit_expr(
    expr: &Expr,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    match expr {
        Expr::Lambda { .. } => Err("Zig backend cannot lower closures yet".to_string()),
        Expr::SliceRange { .. } => {
            Err("Zig backend cannot lower slice-range expressions yet".to_string())
        }
        Expr::Int(value) => Ok(value.to_string()),
        Expr::Float(value) => Ok(zig_float(*value)),
        Expr::Bool(value) => Ok(value.to_string()),
        Expr::String(value) => Ok(zig_string(value)),
        Expr::TraitConst { .. } => {
            Err("Zig backend received an unresolved trait constant".to_string())
        }
        Expr::Var(name) if name.contains("::") => {
            let (enum_name, variant) = name.split_once("::").unwrap();
            if env.is_tagged_union(enum_name) {
                Ok(format!(
                    "{}{{ .{} = {{}} }}",
                    ident(enum_name),
                    ident(variant)
                ))
            } else {
                Ok(format!("{}.{}", ident(enum_name), ident(variant)))
            }
        }
        Expr::Var(name) => {
            let _known = env.values.contains_key(name);
            Ok(ident(name))
        }
        Expr::Unary { op, expr } => Ok(format!("({op}{})", emit_expr(expr, env, structs)?)),
        Expr::Binary { op, left, right }
            if matches!(op.as_str(), "==" | "!=")
                && inferred_zig_type(left, env, structs) == Type::Primitive("str".to_string())
                && inferred_zig_type(right, env, structs) == Type::Primitive("str".to_string()) =>
        {
            let equality = format!(
                "fgx_str_eq({}, {})",
                emit_expr(left, env, structs)?,
                emit_expr(right, env, structs)?
            );
            if op == "==" {
                Ok(equality)
            } else {
                Ok(format!("(!{equality})"))
            }
        }
        Expr::Binary { op, left, right } => Ok(format!(
            "({} {} {})",
            emit_expr(left, env, structs)?,
            op,
            emit_expr(right, env, structs)?
        )),
        Expr::Call { name, args } => {
            if is_cpu_feature_probe(name) || name == "aligned" {
                return Ok("false".to_string());
            }
            if matches!(name.as_str(), "is_some" | "is_none" | "unwrap_or") {
                if let Some(Expr::Call {
                    name: pop_name,
                    args: pop_args,
                }) = args.first()
                {
                    if pop_name == "pop" && pop_args.len() == 1 {
                        let vec = &pop_args[0];
                        let suffix = native_vec_suffix(&inferred_zig_type(vec, env, structs))
                            .ok_or_else(|| {
                                "Zig backend value pop requires a supported local native Vec"
                                    .to_string()
                            })?;
                        let vec = emit_expr(vec, env, structs)?;
                        match (name.as_str(), args.as_slice()) {
                            ("is_some", [_]) => {
                                return Ok(format!("(fgx_vec_{suffix}_pop_value(&{vec}) != null)"));
                            }
                            ("is_none", [_]) => {
                                return Ok(format!("(fgx_vec_{suffix}_pop_value(&{vec}) == null)"));
                            }
                            ("unwrap_or", [_, fallback]) => {
                                return Ok(format!(
                                    "(fgx_vec_{suffix}_pop_value(&{vec}) orelse {})",
                                    emit_expr(fallback, env, structs)?
                                ));
                            }
                            _ => {}
                        }
                    }
                }
                if let Some(option) = args.first() {
                    if native_option_suffix(&inferred_zig_type(option, env, structs)).is_some() {
                        let option = emit_expr(option, env, structs)?;
                        match (name.as_str(), args.as_slice()) {
                            ("is_some", [_]) => return Ok(format!("({option} != null)")),
                            ("is_none", [_]) => return Ok(format!("({option} == null)")),
                            ("unwrap_or", [_, fallback]) => {
                                return Ok(format!(
                                    "({option} orelse {})",
                                    emit_expr(fallback, env, structs)?
                                ));
                            }
                            _ => {}
                        }
                    }
                }
            }
            if matches!(
                name.as_str(),
                "Some"
                    | "None"
                    | "Ok"
                    | "Err"
                    | "is_some"
                    | "is_none"
                    | "is_ok"
                    | "is_err"
                    | "unwrap_or"
            ) {
                return Err(format!(
                    "Zig backend does not lower interpreter-only intrinsic '{name}' yet"
                ));
            }
            let vec_suffix = args
                .first()
                .and_then(|arg| native_vec_suffix(&inferred_zig_type(arg, env, structs)));
            let values = args
                .iter()
                .map(|arg| emit_expr(arg, env, structs))
                .collect::<Result<Vec<_>, _>>()?;
            match (name.as_str(), values.as_slice()) {
                ("vec_new", []) => {
                    return Err(
                        "Zig backend vec_new requires an annotated supported local Vec".to_string(),
                    );
                }
                ("push", [vec, value]) => {
                    let suffix = vec_suffix.ok_or_else(|| {
                        "Zig backend push requires a supported local native Vec".to_string()
                    })?;
                    return Ok(format!("fgx_vec_{suffix}_push(&{vec}, {value})"));
                }
                ("pop", [vec]) => {
                    let suffix = vec_suffix.ok_or_else(|| {
                        "Zig backend pop requires a supported local native Vec".to_string()
                    })?;
                    return Ok(format!("fgx_vec_{suffix}_pop(&{vec})"));
                }
                ("str_len", [value]) => return Ok(format!("fgx_str_len({value})")),
                ("str_contains", [text, needle]) => {
                    return Ok(format!("fgx_str_contains({text}, {needle})"));
                }
                ("vec_new" | "push" | "pop" | "str_len" | "str_contains", _) => {
                    return Err(format!("Zig backend received invalid arity for '{name}'"));
                }
                _ => {}
            }
            if let Some((enum_name, variant)) = name.split_once("::") {
                if env.is_tagged_union(enum_name) {
                    return Ok(match values.first() {
                        Some(value) => {
                            format!("{}{{ .{} = {value} }}", ident(enum_name), ident(variant))
                        }
                        None => format!("{}{{ .{} = {{}} }}", ident(enum_name), ident(variant)),
                    });
                }
                return Ok(format!("{}.{}", ident(enum_name), ident(variant)));
            }
            if let Some(decl) = structs.get(name) {
                let fields = decl
                    .fields
                    .iter()
                    .zip(values.iter())
                    .map(|(field, value)| format!(".{} = {value}", ident(&field.name)))
                    .collect::<Vec<_>>()
                    .join(", ");
                return Ok(format!("{}{{ {fields} }}", ident(name)));
            }
            Ok(format!("{}({})", ident(name), values.join(", ")))
        }
        Expr::Cast { ty, expr } => emit_cast(ty, expr, env, structs),
        Expr::Field { base, field }
            if field == "len"
                && inferred_zig_type(base, env, structs) == Type::Primitive("str".to_string()) =>
        {
            Ok(format!("fgx_str_len({})", emit_expr(base, env, structs)?))
        }
        Expr::Field { base, field } => Ok(format!(
            "{}.{}",
            emit_expr(base, env, structs)?,
            ident(field)
        )),
        Expr::Index { base, index } => {
            let base_text = emit_expr(base, env, structs)?;
            let index_text = emit_expr(index, env, structs)?;
            if is_native_vec(&inferred_zig_type(base, env, structs)) {
                Ok(format!(
                    "{base_text}.data.?[fgx_bounds_index({index_text}, {base_text}.len)]"
                ))
            } else {
                Ok(format!(
                    "{base_text}[fgx_bounds_index({index_text}, {base_text}.len)]"
                ))
            }
        }
    }
}

fn fir_signature_comment(ir: &BackendIr) -> String {
    format!(
        "// FIR signatures: forgentex.backend_ir.v1 package={} version={}\n",
        ir.package, ir.version
    )
}

fn ir_function_for_ast<'a>(
    ir: &'a BackendIr,
    function: &FunctionDecl,
) -> Result<&'a IrFunction, String> {
    ir.modules
        .iter()
        .flat_map(|module| module.functions.iter())
        .find(|candidate| candidate.id == function.id && candidate.name == function.name)
        .ok_or_else(|| format!("FIR function missing for '{}'", function.name))
}

fn ir_enum_for_ast<'a>(ir: &'a BackendIr, decl: &EnumDecl) -> Result<&'a IrEnum, String> {
    ir.modules
        .iter()
        .flat_map(|module| module.enums.iter())
        .find(|candidate| candidate.id == decl.id && candidate.name == decl.name)
        .ok_or_else(|| format!("FIR enum missing for '{}'", decl.name))
}

fn ir_struct_for_ast<'a>(ir: &'a BackendIr, decl: &StructDecl) -> Result<&'a IrStruct, String> {
    ir.modules
        .iter()
        .flat_map(|module| module.structs.iter())
        .find(|candidate| candidate.id == decl.id && candidate.name == decl.name)
        .ok_or_else(|| format!("FIR struct missing for '{}'", decl.name))
}

fn function_signature_from_ir(function: &IrFunction) -> Result<String, String> {
    let visibility = if function.public { "pub " } else { "" };
    let params = function
        .params
        .iter()
        .map(|param| {
            Ok(format!(
                "{}: {}",
                ident(&param.name),
                zig_type_from_ir(&param.ty)?
            ))
        })
        .collect::<Result<Vec<String>, String>>()?
        .join(", ");
    Ok(format!(
        "{visibility}fn {}({params}) {}",
        ident(&function.name),
        zig_type_from_ir(&function.ret)?
    ))
}

fn zig_type_from_ir(ty: &str) -> Result<String, String> {
    zig_type(&Type::parse(ty))
}

fn emit_cast(
    ty: &Type,
    expr: &Expr,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    let target = zig_type(ty)?;
    let value = emit_expr(expr, env, structs)?;
    let source = inferred_zig_type(expr, env, structs);
    if source == *ty {
        return Ok(value);
    }
    if ty.is_float() && source.is_integer() {
        Ok(format!("@as({target}, @floatFromInt({value}))"))
    } else if ty.is_integer() && source.is_float() {
        Ok(format!("@as({target}, @intFromFloat({value}))"))
    } else if ty.is_integer() && source.is_integer() {
        Ok(format!("@as({target}, @intCast({value}))"))
    } else {
        Ok(format!("@as({target}, {value})"))
    }
}

fn zig_type(ty: &Type) -> Result<String, String> {
    match ty {
        Type::Bool => Ok("bool".to_string()),
        Type::Primitive(name) => match name.as_str() {
            "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize"
            | "f32" | "f64" => Ok(name.clone()),
            "str" => Ok("[]const u8".to_string()),
            "$int" => Ok("i64".to_string()),
            "$float" => Ok("f64".to_string()),
            other => Err(format!(
                "Zig backend does not know primitive type '{other}'"
            )),
        },
        Type::Named(name) => Ok(ident(name)),
        ty @ Type::Generic { name, .. } if is_native_vec(ty) => {
            Ok(format!("FgxVec{}", native_vec_title(ty).unwrap()))
        }
        ty @ Type::Generic { name, args }
            if name == "Option" && native_option_suffix(ty).is_some() =>
        {
            Ok(format!("?{}", zig_type(&args[0])?))
        }
        ty @ Type::Generic { name, .. } if name == "Fn" && is_native_function_type(ty) => {
            let (params, ret, _) = ty
                .function_parts()
                .ok_or_else(|| "Zig backend received a malformed function type".to_string())?;
            let params = params
                .iter()
                .map(zig_type)
                .collect::<Result<Vec<_>, _>>()?
                .join(", ");
            Ok(format!("*const fn ({params}) {}", zig_type(ret)?))
        }
        Type::Generic { name, .. } => Err(format!(
            "Zig backend does not lower generic type '{}'",
            name
        )),
        Type::Array { elem, len } => Ok(format!("[{len}]{}", zig_type(elem)?)),
        Type::Slice { mutable, elem } => {
            if *mutable {
                Ok(format!("[]{}", zig_type(elem)?))
            } else {
                Ok(format!("[]const {}", zig_type(elem)?))
            }
        }
        Type::Pointer { mutable, elem } => {
            if *mutable {
                Ok(format!("*{}", zig_type(elem)?))
            } else {
                Ok(format!("*const {}", zig_type(elem)?))
            }
        }
        Type::Void => Ok("void".to_string()),
        Type::Unknown => Ok("*anyopaque".to_string()),
    }
}

fn enum_is_tagged_union_ir(decl: &IrEnum) -> bool {
    decl.variants
        .iter()
        .any(|variant| variant.payload.is_some())
}

fn ensure_zig_lowerable(function: &FunctionDecl) -> Result<(), String> {
    if function.unsafe_fn || function.has_asm() {
        return Err(format!(
            "Zig backend cannot lower unsafe or assembly function '{}'",
            function.name
        ));
    }
    for effect in &function.effects {
        if is_runtime_only_effect(effect)
            && !(effect == "alloc" && function_has_native_vec(function))
        {
            return Err(format!(
                "Zig backend cannot lower runtime effect '{}' in function '{}'",
                effect, function.name
            ));
        }
    }
    Ok(())
}

fn combined_program(project: &Project) -> Program {
    let mut items = Vec::new();
    for module in &project.modules {
        items.extend(module.program.items.clone());
    }
    Program { items }
}

fn function_has_native_vec(function: &FunctionDecl) -> bool {
    stmts_have_native_vec(&function.body)
}

fn stmts_have_native_vec(body: &[crate::ast::Stmt]) -> bool {
    body.iter().any(|stmt| match stmt {
        crate::ast::Stmt::Let {
            ty: Some(ty),
            expr: Expr::Call { name, args },
            ..
        } => is_native_vec(ty) && name == "vec_new" && args.is_empty(),
        crate::ast::Stmt::If {
            then_body,
            else_body,
            ..
        } => stmts_have_native_vec(then_body) || stmts_have_native_vec(else_body),
        crate::ast::Stmt::For { body, .. } | crate::ast::Stmt::While { body, .. } => {
            stmts_have_native_vec(body)
        }
        crate::ast::Stmt::Match { arms, .. } => {
            arms.iter().any(|arm| stmts_have_native_vec(&arm.body))
        }
        _ => false,
    })
}

#[derive(Clone)]
struct Env {
    values: HashMap<String, Type>,
    enums: HashMap<String, IrEnum>,
    function_returns: HashMap<String, Type>,
    return_type: Type,
}

impl Env {
    fn from_params(
        params: &[Param],
        return_type: &Type,
        enums: &HashMap<String, IrEnum>,
        function_returns: &HashMap<String, Type>,
    ) -> Self {
        let values = params
            .iter()
            .map(|param| (param.name.clone(), param.ty.clone()))
            .collect();
        Self {
            values,
            enums: enums.clone(),
            function_returns: function_returns.clone(),
            return_type: return_type.clone(),
        }
    }

    fn insert(&mut self, name: &str, ty: Type) {
        self.values.insert(name.to_string(), ty);
    }

    fn is_tagged_union(&self, enum_name: &str) -> bool {
        self.enums
            .get(enum_name)
            .map(enum_is_tagged_union_ir)
            .unwrap_or(false)
    }

    fn variant_payload(&self, enum_name: &str, variant_name: &str) -> Option<Type> {
        self.enums
            .get(enum_name)?
            .variants
            .iter()
            .find(|variant| variant.name == variant_name)?
            .payload
            .as_deref()
            .map(Type::parse)
    }
}

fn inferred_zig_type(expr: &Expr, env: &Env, structs: &HashMap<String, StructDecl>) -> Type {
    match expr {
        Expr::Lambda { .. } => Type::Unknown,
        Expr::Int(_) => Type::Primitive("i64".to_string()),
        Expr::Float(_) => Type::Primitive("f64".to_string()),
        Expr::Bool(_) => Type::Bool,
        Expr::String(_) => Type::Primitive("str".to_string()),
        Expr::TraitConst { .. } => Type::Unknown,
        Expr::Var(name) if name.contains("::") => {
            Type::Named(name.split("::").next().unwrap_or(name).to_string())
        }
        Expr::Var(name) => env.values.get(name).cloned().unwrap_or(Type::Unknown),
        Expr::Call { name, .. } if name.contains("::") => {
            Type::Named(name.split("::").next().unwrap_or(name).to_string())
        }
        Expr::Call { name, .. } if structs.contains_key(name) => Type::Named(name.clone()),
        Expr::Call { name, .. } => env
            .function_returns
            .get(name)
            .cloned()
            .unwrap_or(Type::Unknown),
        Expr::Cast { ty, .. } => ty.clone(),
        Expr::Field { base, field } if field == "len" => {
            let base_ty = inferred_zig_type(base, env, structs);
            if matches!(base_ty, Type::Slice { .. } | Type::Array { .. })
                || is_native_vec(&base_ty)
                || base_ty == Type::Primitive("str".to_string())
            {
                Type::Primitive("usize".to_string())
            } else {
                Type::Unknown
            }
        }
        Expr::Index { base, .. } => inferred_zig_type(base, env, structs)
            .element_type()
            .unwrap_or(Type::Unknown),
        Expr::SliceRange { base, .. } => match inferred_zig_type(base, env, structs) {
            Type::Slice { mutable, elem } => Type::Slice { mutable, elem },
            Type::Array { elem, .. } => Type::Slice {
                mutable: false,
                elem,
            },
            _ => Type::Unknown,
        },
        Expr::Unary { expr, .. } => inferred_zig_type(expr, env, structs),
        Expr::Binary { left, right, .. } => {
            let left = inferred_zig_type(left, env, structs);
            let right = inferred_zig_type(right, env, structs);
            if left == right {
                left
            } else if left.is_float() || right.is_float() {
                Type::Primitive("f64".to_string())
            } else {
                Type::Primitive("i64".to_string())
            }
        }
        Expr::Field { .. } => Type::Unknown,
    }
}

fn native_vec_suffix(ty: &Type) -> Option<String> {
    let Type::Generic { name, args } = ty else {
        return None;
    };
    let [element] = args.as_slice() else {
        return None;
    };
    if name != "Vec" {
        return None;
    }
    match element {
        Type::Bool => Some("bool".to_string()),
        Type::Primitive(element) => match element.as_str() {
            "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize"
            | "f32" | "f64" | "str" => Some(element.clone()),
            _ => None,
        },
        Type::Named(element) => Some(ident(element)),
        Type::Slice {
            mutable: false,
            elem,
        } if native_vec_slice_element(elem) => {
            Some(format!("slice_{}", native_vec_slice_element_suffix(elem)?))
        }
        element @ Type::Array { elem, len } if is_native_vec_array_element(element) => Some(
            format!("array_{}_{}", native_vec_array_component_suffix(elem)?, len),
        ),
        _ => None,
    }
}

fn native_option_suffix(ty: &Type) -> Option<String> {
    let Type::Generic { name, args } = ty else {
        return None;
    };
    if name != "Option" || args.len() != 1 {
        return None;
    }
    native_vec_suffix(&Type::Generic {
        name: "Vec".to_string(),
        args: args.clone(),
    })
}

fn is_native_option_constructor(expr: &Expr) -> bool {
    matches!(expr, Expr::Call { name, args } if (name == "Some" && args.len() == 1) || (name == "None" && args.is_empty()))
}

fn emit_native_option_constructor(
    expr: &Expr,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    match expr {
        Expr::Call { name, args } if name == "Some" && args.len() == 1 => {
            emit_expr(&args[0], env, structs)
        }
        Expr::Call { name, args } if name == "None" && args.is_empty() => Ok("null".to_string()),
        _ => Err("Zig backend received an invalid Option constructor".to_string()),
    }
}

fn native_vec_slice_element(ty: &Type) -> bool {
    native_vec_slice_element_suffix(ty).is_some()
}

fn native_vec_slice_element_suffix(ty: &Type) -> Option<&'static str> {
    match ty {
        Type::Bool => Some("bool"),
        Type::Primitive(element) => match element.as_str() {
            "i8" => Some("i8"),
            "i16" => Some("i16"),
            "i32" => Some("i32"),
            "i64" => Some("i64"),
            "isize" => Some("isize"),
            "u8" => Some("u8"),
            "u16" => Some("u16"),
            "u32" => Some("u32"),
            "u64" => Some("u64"),
            "usize" => Some("usize"),
            "f32" => Some("f32"),
            "f64" => Some("f64"),
            _ => None,
        },
        _ => None,
    }
}

fn native_vec_array_component_suffix(ty: &Type) -> Option<String> {
    match ty {
        Type::Array { elem, len } => Some(format!(
            "array_{}_{}",
            native_vec_array_component_suffix(elem)?,
            len
        )),
        Type::Primitive(name) if name == "str" => Some("str".to_string()),
        Type::Named(name) => Some(ident(name)),
        Type::Slice {
            mutable: false,
            elem,
        } if native_vec_slice_element(elem) => {
            Some(format!("slice_{}", native_vec_slice_element_suffix(elem)?))
        }
        _ => native_vec_slice_element_suffix(ty).map(str::to_string),
    }
}

fn native_vec_title(ty: &Type) -> Option<String> {
    if let Type::Generic { name, args } = ty {
        if name == "Vec" {
            if let [element @ Type::Array { .. }] = args.as_slice() {
                return native_vec_array_title(element);
            }
        }
    }
    let suffix = native_vec_suffix(ty)?;
    Some(match suffix.as_str() {
        "bool" => "Bool".to_string(),
        "i8" => "I8".to_string(),
        "u8" => "U8".to_string(),
        "i16" => "I16".to_string(),
        "i32" => "I32".to_string(),
        "i64" => "I64".to_string(),
        "isize" => "Isize".to_string(),
        "u16" => "U16".to_string(),
        "u32" => "U32".to_string(),
        "u64" => "U64".to_string(),
        "usize" => "Usize".to_string(),
        "f32" => "F32".to_string(),
        "f64" => "F64".to_string(),
        "str" => "Str".to_string(),
        "slice_bool" => "SliceBool".to_string(),
        "slice_i8" => "SliceI8".to_string(),
        "slice_i16" => "SliceI16".to_string(),
        "slice_i32" => "SliceI32".to_string(),
        "slice_i64" => "SliceI64".to_string(),
        "slice_isize" => "SliceIsize".to_string(),
        "slice_u8" => "SliceU8".to_string(),
        "slice_u16" => "SliceU16".to_string(),
        "slice_u32" => "SliceU32".to_string(),
        "slice_u64" => "SliceU64".to_string(),
        "slice_usize" => "SliceUsize".to_string(),
        "slice_f32" => "SliceF32".to_string(),
        "slice_f64" => "SliceF64".to_string(),
        _ => suffix,
    })
}

fn native_vec_array_title(ty: &Type) -> Option<String> {
    if !is_native_vec_array_element(ty) {
        return None;
    }
    native_vec_array_component_title(ty)
}

fn native_vec_array_component_title(ty: &Type) -> Option<String> {
    match ty {
        Type::Array { elem, len } => Some(format!(
            "Array{}_{}",
            native_vec_array_component_title(elem)?,
            len
        )),
        Type::Primitive(name) if name == "str" => Some("Str".to_string()),
        Type::Named(name) => Some(ident(name)),
        Type::Slice {
            mutable: false,
            elem,
        } if native_vec_slice_element(elem) => {
            Some(format!("Slice{}", native_vec_array_component_title(elem)?))
        }
        _ => Some(
            match native_vec_slice_element_suffix(ty)? {
                "bool" => "Bool",
                "i8" => "I8",
                "i16" => "I16",
                "i32" => "I32",
                "i64" => "I64",
                "isize" => "Isize",
                "u8" => "U8",
                "u16" => "U16",
                "u32" => "U32",
                "u64" => "U64",
                "usize" => "Usize",
                "f32" => "F32",
                "f64" => "F64",
                _ => return None,
            }
            .to_string(),
        ),
    }
}

fn native_vec_array_layouts(program: &Program) -> BTreeMap<String, Type> {
    let mut layouts = BTreeMap::new();
    for function in program.functions() {
        collect_native_vec_array_layouts(&function.body, &mut layouts);
    }
    layouts
}

fn collect_native_vec_array_layouts(
    body: &[crate::ast::Stmt],
    layouts: &mut BTreeMap<String, Type>,
) {
    for stmt in body {
        match stmt {
            crate::ast::Stmt::Let {
                ty: Some(ty @ Type::Generic { name, args }),
                ..
            } if name == "Vec" => {
                if let [element @ Type::Array { .. }] = args.as_slice() {
                    if let Some(suffix) = native_vec_suffix(ty) {
                        layouts.insert(suffix, element.clone());
                    }
                }
            }
            crate::ast::Stmt::If {
                then_body,
                else_body,
                ..
            } => {
                collect_native_vec_array_layouts(then_body, layouts);
                collect_native_vec_array_layouts(else_body, layouts);
            }
            crate::ast::Stmt::For { body, .. } | crate::ast::Stmt::While { body, .. } => {
                collect_native_vec_array_layouts(body, layouts);
            }
            crate::ast::Stmt::Match { arms, .. } => {
                for arm in arms {
                    collect_native_vec_array_layouts(&arm.body, layouts);
                }
            }
            crate::ast::Stmt::Let { .. }
            | crate::ast::Stmt::Return(_)
            | crate::ast::Stmt::Break
            | crate::ast::Stmt::Continue
            | crate::ast::Stmt::Require(_)
            | crate::ast::Stmt::Assign { .. }
            | crate::ast::Stmt::Expr(_)
            | crate::ast::Stmt::Asm(_) => {}
        }
    }
}

fn is_native_vec(ty: &Type) -> bool {
    native_vec_suffix(ty).is_some()
}

fn is_runtime_only_effect(effect: &str) -> bool {
    effect == "alloc"
        || effect.starts_with("alloc.")
        || effect.starts_with("io.")
        || effect.starts_with("fs.")
        || effect.starts_with("network.")
        || effect.starts_with("crypto.")
        || effect.starts_with("ledger.")
        || effect.starts_with("agent.")
        || effect.starts_with("concurrency.")
        || effect == "serialize"
        || effect == "stream"
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

fn ident(name: &str) -> String {
    let mut out = String::new();
    for (idx, ch) in name.chars().enumerate() {
        if ch == '_' || ch.is_ascii_alphanumeric() {
            if idx == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        "_".to_string()
    } else {
        out
    }
}

fn package_ident(name: &str) -> String {
    ident(&name.replace('-', "_"))
}

fn zig_float(value: f64) -> String {
    let mut text = value.to_string();
    if !text.contains('.') {
        text.push_str(".0");
    }
    text
}

fn zig_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}
