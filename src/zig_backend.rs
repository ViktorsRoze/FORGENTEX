use std::collections::{BTreeSet, HashMap};
use std::fs;
use std::path::{Path, PathBuf};

use crate::ast::{Expr, FunctionDecl, Param, Program, Stmt, StructDecl, Type};
use crate::diag::diagnostics_to_json;
use crate::project::{check_project, load_project, Project, PublicSymbol};
use crate::targets::is_cpu_feature_probe;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ZigBuildArtifacts {
    pub source: PathBuf,
}

pub fn build_zig_project(input: &Path, out_dir: &Path) -> Result<ZigBuildArtifacts, String> {
    let diagnostics = check_project(input)?;
    if !diagnostics.is_empty() {
        return Err(format!(
            "project has diagnostics and was not lowered:\n{}",
            diagnostics_to_json(&diagnostics)
        ));
    }
    let project = load_project(input)?;
    let package = package_ident(&project.manifest.name);
    let source_name = format!("{package}.zig");
    let source = generate_source(&project)?;

    fs::create_dir_all(out_dir)
        .map_err(|err| format!("failed to create {}: {err}", out_dir.display()))?;
    let source_path = out_dir.join(&source_name);
    fs::write(&source_path, source)
        .map_err(|err| format!("failed to write {}: {err}", source_path.display()))?;
    Ok(ZigBuildArtifacts {
        source: source_path,
    })
}

pub fn generate_zig_for_project(input: &Path) -> Result<String, String> {
    let diagnostics = check_project(input)?;
    if !diagnostics.is_empty() {
        return Err(format!(
            "project has diagnostics and was not lowered:\n{}",
            diagnostics_to_json(&diagnostics)
        ));
    }
    let project = load_project(input)?;
    generate_source(&project)
}

fn generate_source(project: &Project) -> Result<String, String> {
    let program = combined_program(project);
    let public = public_symbol_set(project);
    let structs = program
        .structs()
        .map(|decl| (decl.name.clone(), decl.clone()))
        .collect::<HashMap<_, _>>();
    let mut out = String::new();
    out.push_str("// Generated by fgx build --backend zig.\n");
    out.push_str("// Zig compiler invocation and build.zig generation are deferred.\n\n");
    out.push_str("fn fgx_trap(code: []const u8) noreturn {\n");
    out.push_str("    @panic(code);\n");
    out.push_str("}\n\n");
    out.push_str("fn fgx_bounds_index(index: usize, len: usize) usize {\n");
    out.push_str("    if (index >= len) fgx_trap(\"index_out_of_bounds\");\n");
    out.push_str("    return index;\n");
    out.push_str("}\n\n");

    for decl in program.structs() {
        out.push_str(&emit_struct_decl(decl, &public)?);
        out.push('\n');
    }

    for function in program.functions() {
        out.push_str(&emit_function(function, &structs, &public)?);
        out.push('\n');
    }
    Ok(out)
}

fn emit_struct_decl(decl: &StructDecl, public: &BTreeSet<String>) -> Result<String, String> {
    let visibility = if public.contains(&format!("struct:{}", decl.name)) {
        "pub "
    } else {
        ""
    };
    let mut out = String::new();
    out.push_str(&format!(
        "{visibility}const {} = struct {{\n",
        ident(&decl.name)
    ));
    for field in &decl.fields {
        out.push_str(&format!(
            "    {}: {},\n",
            ident(&field.name),
            zig_type(&field.ty)?
        ));
    }
    out.push_str("};\n");
    Ok(out)
}

fn emit_function(
    function: &FunctionDecl,
    structs: &HashMap<String, StructDecl>,
    public: &BTreeSet<String>,
) -> Result<String, String> {
    ensure_zig_lowerable(function)?;
    let mut env = Env::from_params(&function.params);
    let mut out = String::new();
    out.push_str(&function_signature(function, public)?);
    out.push_str(" {\n");
    for stmt in &function.body {
        emit_stmt(stmt, 1, &mut env, structs, &mut out)?;
    }
    if matches!(function.ret, Type::Void) && !function.body.iter().any(is_return_stmt) {
        out.push_str("    return;\n");
    }
    out.push_str("}\n");
    Ok(out)
}

fn emit_stmt(
    stmt: &Stmt,
    level: usize,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<(), String> {
    let pad = indent(level);
    match stmt {
        Stmt::Let { name, ty, expr } => {
            let ty = ty
                .clone()
                .unwrap_or_else(|| inferred_zig_type(expr, env, structs));
            let expr = emit_expr(expr, env, structs)?;
            out.push_str(&format!(
                "{pad}var {}: {} = {expr};\n",
                ident(name),
                zig_type(&ty)?
            ));
            env.insert(name, ty);
        }
        Stmt::Return(Some(expr)) => {
            out.push_str(&format!(
                "{pad}return {};\n",
                emit_expr(expr, env, structs)?
            ));
        }
        Stmt::Return(None) => out.push_str(&format!("{pad}return;\n")),
        Stmt::Require(expr) => {
            out.push_str(&format!(
                "{pad}if (!({})) fgx_trap(\"require_failed\");\n",
                emit_expr(expr, env, structs)?
            ));
        }
        Stmt::If { cond, then_body } => {
            out.push_str(&format!(
                "{pad}if ({}) {{\n",
                emit_expr(cond, env, structs)?
            ));
            let mut branch_env = env.clone();
            for stmt in then_body {
                emit_stmt(stmt, level + 1, &mut branch_env, structs, out)?;
            }
            out.push_str(&format!("{pad}}}\n"));
        }
        Stmt::For {
            var,
            start,
            end,
            body,
        } => {
            let start = emit_expr(start, env, structs)?;
            let end = emit_expr(end, env, structs)?;
            out.push_str(&format!("{pad}var {}: usize = {start};\n", ident(var)));
            out.push_str(&format!(
                "{pad}while ({} < {end}) : ({} += 1) {{\n",
                ident(var),
                ident(var)
            ));
            let mut loop_env = env.clone();
            loop_env.insert(var, Type::Primitive("usize".to_string()));
            for stmt in body {
                emit_stmt(stmt, level + 1, &mut loop_env, structs, out)?;
            }
            out.push_str(&format!("{pad}}}\n"));
        }
        Stmt::Assign { target, expr } => {
            let value = emit_expr(expr, env, structs)?;
            match target {
                Expr::Index { base, index } => {
                    let base_text = emit_expr(base, env, structs)?;
                    let index_text = emit_expr(index, env, structs)?;
                    out.push_str(&format!(
                        "{pad}{base_text}[fgx_bounds_index({index_text}, {base_text}.len)] = {value};\n"
                    ));
                }
                _ => out.push_str(&format!(
                    "{pad}{} = {value};\n",
                    emit_expr(target, env, structs)?
                )),
            }
        }
        Stmt::Expr(expr) => out.push_str(&format!("{pad}{};\n", emit_expr(expr, env, structs)?)),
        Stmt::Asm(_) => return Err("Zig backend cannot lower assembly blocks".to_string()),
    }
    Ok(())
}

fn emit_expr(
    expr: &Expr,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    match expr {
        Expr::Int(value) => Ok(value.to_string()),
        Expr::Float(value) => Ok(zig_float(*value)),
        Expr::Bool(value) => Ok(value.to_string()),
        Expr::String(value) => Ok(zig_string(value)),
        Expr::Var(name) => {
            let _known = env.values.contains_key(name);
            Ok(ident(name))
        }
        Expr::Unary { op, expr } => Ok(format!("({op}{})", emit_expr(expr, env, structs)?)),
        Expr::Binary { op, left, right } => Ok(format!(
            "({} {} {})",
            emit_expr(left, env, structs)?,
            op,
            emit_expr(right, env, structs)?
        )),
        Expr::Call { name, args } => {
            if is_cpu_feature_probe(name) || name == "aligned" {
                return Ok("false".to_string());
            }
            if matches!(
                name.as_str(),
                "Some"
                    | "None"
                    | "Ok"
                    | "Err"
                    | "is_some"
                    | "is_none"
                    | "is_ok"
                    | "is_err"
                    | "unwrap_or"
            ) {
                return Err(format!(
                    "Zig backend does not lower interpreter-only intrinsic '{name}' yet"
                ));
            }
            let values = args
                .iter()
                .map(|arg| emit_expr(arg, env, structs))
                .collect::<Result<Vec<_>, _>>()?;
            if let Some(decl) = structs.get(name) {
                let fields = decl
                    .fields
                    .iter()
                    .zip(values.iter())
                    .map(|(field, value)| format!(".{} = {value}", ident(&field.name)))
                    .collect::<Vec<_>>()
                    .join(", ");
                return Ok(format!("{}{{ {fields} }}", ident(name)));
            }
            Ok(format!("{}({})", ident(name), values.join(", ")))
        }
        Expr::Cast { ty, expr } => emit_cast(ty, expr, env, structs),
        Expr::Field { base, field } => Ok(format!(
            "{}.{}",
            emit_expr(base, env, structs)?,
            ident(field)
        )),
        Expr::Index { base, index } => {
            let base_text = emit_expr(base, env, structs)?;
            let index_text = emit_expr(index, env, structs)?;
            Ok(format!(
                "{base_text}[fgx_bounds_index({index_text}, {base_text}.len)]"
            ))
        }
    }
}

fn function_signature(
    function: &FunctionDecl,
    public: &BTreeSet<String>,
) -> Result<String, String> {
    let visibility = if public.contains(&format!("fn:{}", function.name)) {
        "pub "
    } else {
        ""
    };
    let params = function
        .params
        .iter()
        .map(|param| Ok(format!("{}: {}", ident(&param.name), zig_type(&param.ty)?)))
        .collect::<Result<Vec<String>, String>>()?
        .join(", ");
    Ok(format!(
        "{visibility}fn {}({params}) {}",
        ident(&function.name),
        zig_type(&function.ret)?
    ))
}

fn emit_cast(
    ty: &Type,
    expr: &Expr,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    let target = zig_type(ty)?;
    let value = emit_expr(expr, env, structs)?;
    let source = inferred_zig_type(expr, env, structs);
    if source == *ty {
        return Ok(value);
    }
    if ty.is_float() && source.is_integer() {
        Ok(format!("@as({target}, @floatFromInt({value}))"))
    } else if ty.is_integer() && source.is_float() {
        Ok(format!("@as({target}, @intFromFloat({value}))"))
    } else if ty.is_integer() && source.is_integer() {
        Ok(format!("@as({target}, @intCast({value}))"))
    } else {
        Ok(format!("@as({target}, {value})"))
    }
}

fn zig_type(ty: &Type) -> Result<String, String> {
    match ty {
        Type::Bool => Ok("bool".to_string()),
        Type::Primitive(name) => match name.as_str() {
            "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize"
            | "f32" | "f64" => Ok(name.clone()),
            "str" => Ok("[]const u8".to_string()),
            "$int" => Ok("i64".to_string()),
            "$float" => Ok("f64".to_string()),
            other => Err(format!(
                "Zig backend does not know primitive type '{other}'"
            )),
        },
        Type::Named(name) => Ok(ident(name)),
        Type::Generic { name, .. } => Err(format!(
            "Zig backend does not lower generic type '{}'",
            name
        )),
        Type::Array { elem, len } => Ok(format!("[{len}]{}", zig_type(elem)?)),
        Type::Slice { mutable, elem } => {
            if *mutable {
                Ok(format!("[]{}", zig_type(elem)?))
            } else {
                Ok(format!("[]const {}", zig_type(elem)?))
            }
        }
        Type::Pointer { mutable, elem } => {
            if *mutable {
                Ok(format!("*{}", zig_type(elem)?))
            } else {
                Ok(format!("*const {}", zig_type(elem)?))
            }
        }
        Type::Void => Ok("void".to_string()),
        Type::Unknown => Ok("*anyopaque".to_string()),
    }
}

fn ensure_zig_lowerable(function: &FunctionDecl) -> Result<(), String> {
    if function.unsafe_fn || function.has_asm() {
        return Err(format!(
            "Zig backend cannot lower unsafe or assembly function '{}'",
            function.name
        ));
    }
    for effect in &function.effects {
        if is_runtime_only_effect(effect) {
            return Err(format!(
                "Zig backend cannot lower runtime effect '{}' in function '{}'",
                effect, function.name
            ));
        }
    }
    Ok(())
}

fn combined_program(project: &Project) -> Program {
    let mut items = Vec::new();
    for module in &project.modules {
        items.extend(module.program.items.clone());
    }
    Program { items }
}

fn public_symbol_set(project: &Project) -> BTreeSet<String> {
    project
        .modules
        .iter()
        .filter(|module| !module.standard && !module.dependency)
        .flat_map(|module| module.public_symbols.iter())
        .map(public_symbol_key)
        .collect()
}

fn public_symbol_key(symbol: &PublicSymbol) -> String {
    format!("{}:{}", symbol.kind, symbol.name)
}

#[derive(Clone, Default)]
struct Env {
    values: HashMap<String, Type>,
}

impl Env {
    fn from_params(params: &[Param]) -> Self {
        let values = params
            .iter()
            .map(|param| (param.name.clone(), param.ty.clone()))
            .collect();
        Self { values }
    }

    fn insert(&mut self, name: &str, ty: Type) {
        self.values.insert(name.to_string(), ty);
    }
}

fn inferred_zig_type(expr: &Expr, env: &Env, structs: &HashMap<String, StructDecl>) -> Type {
    match expr {
        Expr::Int(_) => Type::Primitive("i64".to_string()),
        Expr::Float(_) => Type::Primitive("f64".to_string()),
        Expr::Bool(_) => Type::Bool,
        Expr::String(_) => Type::Primitive("str".to_string()),
        Expr::Var(name) => env.values.get(name).cloned().unwrap_or(Type::Unknown),
        Expr::Call { name, .. } if structs.contains_key(name) => Type::Named(name.clone()),
        Expr::Call { .. } => Type::Unknown,
        Expr::Cast { ty, .. } => ty.clone(),
        Expr::Field { base, field } if field == "len" => {
            let base_ty = inferred_zig_type(base, env, structs);
            if matches!(base_ty, Type::Slice { .. } | Type::Array { .. }) {
                Type::Primitive("usize".to_string())
            } else {
                Type::Unknown
            }
        }
        Expr::Index { base, .. } => inferred_zig_type(base, env, structs)
            .element_type()
            .unwrap_or(Type::Unknown),
        Expr::Unary { expr, .. } => inferred_zig_type(expr, env, structs),
        Expr::Binary { left, right, .. } => {
            let left = inferred_zig_type(left, env, structs);
            let right = inferred_zig_type(right, env, structs);
            if left == right {
                left
            } else if left.is_float() || right.is_float() {
                Type::Primitive("f64".to_string())
            } else {
                Type::Primitive("i64".to_string())
            }
        }
        Expr::Field { .. } => Type::Unknown,
    }
}

fn is_runtime_only_effect(effect: &str) -> bool {
    effect == "alloc"
        || effect.starts_with("alloc.")
        || effect.starts_with("io.")
        || effect.starts_with("fs.")
        || effect.starts_with("network.")
        || effect.starts_with("crypto.")
        || effect.starts_with("ledger.")
        || effect.starts_with("agent.")
        || effect == "serialize"
        || effect == "stream"
}

fn is_return_stmt(stmt: &Stmt) -> bool {
    matches!(stmt, Stmt::Return(_))
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

fn ident(name: &str) -> String {
    let mut out = String::new();
    for (idx, ch) in name.chars().enumerate() {
        if ch == '_' || ch.is_ascii_alphanumeric() {
            if idx == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        "_".to_string()
    } else {
        out
    }
}

fn package_ident(name: &str) -> String {
    ident(&name.replace('-', "_"))
}

fn zig_float(value: f64) -> String {
    let mut text = value.to_string();
    if !text.contains('.') {
        text.push_str(".0");
    }
    text
}

fn zig_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}
