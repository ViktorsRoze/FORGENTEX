#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CBuildArtifacts {
    pub header: PathBuf,
    pub source: PathBuf,
}

pub fn build_c_project(input: &Path, out_dir: &Path) -> Result<CBuildArtifacts, String> {
    let (artifacts, _ir, _report) = build_c_project_inner(input, out_dir, false)?;
    Ok(artifacts)
}

/// `fgx build --opt`: optimize the loaded project (v3.2), then lower FIR from
/// the optimized ASTs (so bodies, contracts, and receipts all reflect it) and
/// emit. Returns the artifacts, the optimized FIR, and the pass report.
pub fn build_c_project_opt(
    input: &Path,
    out_dir: &Path,
) -> Result<(CBuildArtifacts, BackendIr, crate::optimize::OptReport), String> {
    let (artifacts, ir, report) = build_c_project_inner(input, out_dir, true)?;
    Ok((artifacts, ir, report.unwrap_or_default()))
}

fn build_c_project_inner(
    input: &Path,
    out_dir: &Path,
    optimize: bool,
) -> Result<
    (
        CBuildArtifacts,
        BackendIr,
        Option<crate::optimize::OptReport>,
    ),
    String,
> {
    let diagnostics = check_project(input)?;
    if !diagnostics.is_empty() {
        return Err(format!(
            "project has diagnostics and was not lowered:\n{}",
            diagnostics_to_json(&diagnostics)
        ));
    }
    let mut project = load_project(input)?;
    crate::monomorphize::monomorphize_project(&mut project)?;
    crate::closure_lower::lower_non_capturing_closures(&mut project);
    let report = optimize.then(|| crate::optimize::optimize_project(&mut project));
    let ir = crate::backend::generate_ready_backend_ir_from_project(&project, "c")?;
    let package = package_ident(&project.manifest.name);
    let header_name = format!("{package}.h");
    let source_name = format!("{package}.c");
    let header = generate_header(&project, &header_name, &ir)?;
    let source = generate_source(&project, &header_name, &ir)?;

    fs::create_dir_all(out_dir)
        .map_err(|err| format!("failed to create {}: {err}", out_dir.display()))?;
    let header_path = out_dir.join(&header_name);
    let source_path = out_dir.join(&source_name);
    fs::write(&header_path, header)
        .map_err(|err| format!("failed to write {}: {err}", header_path.display()))?;
    fs::write(&source_path, source)
        .map_err(|err| format!("failed to write {}: {err}", source_path.display()))?;
    Ok((
        CBuildArtifacts {
            header: header_path,
            source: source_path,
        },
        ir,
        report,
    ))
}

pub fn generate_c_for_project(input: &Path) -> Result<(String, String), String> {
    let diagnostics = check_project(input)?;
    if !diagnostics.is_empty() {
        return Err(format!(
            "project has diagnostics and was not lowered:\n{}",
            diagnostics_to_json(&diagnostics)
        ));
    }
    let mut project = load_project(input)?;
    crate::monomorphize::monomorphize_project(&mut project)?;
    crate::closure_lower::lower_non_capturing_closures(&mut project);
    let ir = crate::backend::generate_ready_backend_ir_from_project(&project, "c")?;
    let header_name = format!("{}.h", package_ident(&project.manifest.name));
    Ok((
        generate_header(&project, &header_name, &ir)?,
        generate_source(&project, &header_name, &ir)?,
    ))
}

fn generate_header(project: &Project, header_name: &str, ir: &BackendIr) -> Result<String, String> {
    let guard = header_guard(header_name);
    let program = combined_program(project);
    let mut types = TypeRegistry::default();
    types.collect_program(&program);

    let mut out = String::new();
    out.push_str("/* Generated by fgx build --backend c. */\n");
    out.push_str(&fir_signature_comment(ir));
    out.push_str(&format!("#ifndef {guard}\n#define {guard}\n\n"));
    out.push_str(
        "#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n#include <stdlib.h>\n#include <string.h>\n\n",
    );
    out.push_str("static inline void fgx_trap(const char *code) { (void)code; abort(); }\n");
    out.push_str("static inline size_t fgx_bounds_index(size_t index, size_t len) { if (index >= len) fgx_trap(\"index_out_of_bounds\"); return index; }\n");
    out.push_str("static inline int64_t fgx_checked_i64_add(int64_t a, int64_t b) { if ((b > 0 && a > INT64_MAX - b) || (b < 0 && a < INT64_MIN - b)) fgx_trap(\"integer_overflow\"); return a + b; }\n");
    out.push_str("static inline int64_t fgx_checked_i64_sub(int64_t a, int64_t b) { if ((b < 0 && a > INT64_MAX + b) || (b > 0 && a < INT64_MIN + b)) fgx_trap(\"integer_overflow\"); return a - b; }\n");
    out.push_str("static inline int64_t fgx_checked_i64_mul(int64_t a, int64_t b) { if (a != 0 && b != 0 && (a > INT64_MAX / b || a < INT64_MIN / b)) fgx_trap(\"integer_overflow\"); return a * b; }\n");
    out.push_str("#define FGX_STR_MAX_BYTES ((size_t)16777216)\n");
    out.push_str("static inline size_t fgx_str_len(const char *value) { if (!value) fgx_trap(\"null_string\"); size_t len = 0; while (len < FGX_STR_MAX_BYTES && value[len] != '\\0') ++len; if (len == FGX_STR_MAX_BYTES) fgx_trap(\"string_too_large\"); return len; }\n");
    out.push_str("static inline bool fgx_str_eq(const char *left, const char *right) { size_t left_len = fgx_str_len(left); size_t right_len = fgx_str_len(right); return left_len == right_len && memcmp(left, right, left_len) == 0; }\n");
    out.push_str("static inline bool fgx_str_contains(const char *text, const char *needle) { size_t text_len = fgx_str_len(text); size_t needle_len = fgx_str_len(needle); if (needle_len == 0) return true; if (needle_len > text_len) return false; for (size_t i = 0; i <= text_len - needle_len; ++i) if (memcmp(text + i, needle, needle_len) == 0) return true; return false; }\n");
    for (suffix, c_element) in [
        ("bool", "bool"),
        ("i8", "int8_t"),
        ("i16", "int16_t"),
        ("i32", "int32_t"),
        ("i64", "int64_t"),
        ("isize", "ptrdiff_t"),
        ("u8", "uint8_t"),
        ("u16", "uint16_t"),
        ("u32", "uint32_t"),
        ("u64", "uint64_t"),
        ("usize", "size_t"),
        ("f32", "float"),
        ("f64", "double"),
        ("str", "const char *"),
    ] {
        out.push_str(&emit_native_vec_decl(suffix, c_element));
    }
    out.push('\n');

    for typedef in types.typedefs() {
        out.push_str(&typedef);
        out.push('\n');
    }
    if !types.is_empty() {
        out.push('\n');
    }

    for ((_, len), elem) in &types.arrays {
        let array = Type::Array {
            elem: Box::new(elem.clone()),
            len: *len,
        };
        if is_native_vec_array_element(&array) && array_named_leaf(&array).is_none() {
            let suffix = format!("array_{}_{}", type_suffix(elem)?, len);
            let element = array_type_name(elem, *len)?;
            out.push_str(&emit_native_vec_decl(&suffix, &element));
        }
    }

    for ((mutable, _), elem) in &types.slices {
        if !*mutable && native_vec_slice_element(elem) {
            let suffix = format!("slice_{}", type_suffix(elem)?);
            let element = slice_type_name(elem, false)?;
            out.push_str(&emit_native_vec_decl(&suffix, &element));
        }
    }

    for decl in program.enums() {
        out.push_str(&emit_enum_decl_from_ir(ir_enum_for_ast(ir, decl)?)?);
        out.push('\n');
    }

    for decl in program.enums() {
        emit_native_named_array_layouts(&types, &decl.name, &mut out)?;
    }

    for decl in program.enums() {
        let suffix = ident(&decl.name);
        let element = ident(&decl.name);
        out.push_str(&emit_native_vec_decl(&suffix, &element));
    }

    for decl in program.structs() {
        let ir_struct = ir_struct_for_ast(ir, decl)?;
        if ir_struct.public {
            out.push_str(&emit_struct_decl_from_ir(ir_struct)?);
            out.push('\n');
            emit_native_named_array_layouts(&types, &decl.name, &mut out)?;
        }
    }

    for decl in program.structs() {
        let ir_struct = ir_struct_for_ast(ir, decl)?;
        if ir_struct.public {
            let suffix = ident(&decl.name);
            out.push_str(&emit_native_vec_decl(&suffix, &suffix));
        }
    }

    for function in program.functions() {
        let ir_function = ir_function_for_ast(ir, function)?;
        if ir_function.public {
            ensure_c_lowerable(function)?;
            out.push_str(&format!("{};\n", function_signature_from_ir(ir_function)?));
        }
    }
    out.push_str(&format!("\n#endif /* {guard} */\n"));
    Ok(out)
}

fn emit_native_vec_decl(suffix: &str, element: &str) -> String {
    let upper = suffix.to_ascii_uppercase();
    format!(
        "#define FGX_VEC_{upper}_MAX_ELEMENTS ((size_t)1048576)\n\
typedef struct {{ {element} *data; size_t len; size_t capacity; }} fgx_vec_{suffix};\n\
typedef struct {{ bool has_value; {element} value; }} fgx_option_{suffix};\n\
static inline fgx_vec_{suffix} fgx_vec_{suffix}_new(void) {{ return (fgx_vec_{suffix}){{ .data = NULL, .len = 0, .capacity = 0 }}; }}\n\
static inline void fgx_vec_{suffix}_free(fgx_vec_{suffix} *vec) {{ free(vec->data); vec->data = NULL; vec->len = 0; vec->capacity = 0; }}\n\
static inline void fgx_vec_{suffix}_reserve_for_push(fgx_vec_{suffix} *vec) {{ if (vec->len >= FGX_VEC_{upper}_MAX_ELEMENTS) fgx_trap(\"vec_capacity_exceeded\"); if (vec->len < vec->capacity) return; size_t next = vec->capacity == 0 ? 4 : vec->capacity * 2; if (next > FGX_VEC_{upper}_MAX_ELEMENTS) next = FGX_VEC_{upper}_MAX_ELEMENTS; {element} *data = ({element} *)realloc(vec->data, next * sizeof({element})); if (!data) fgx_trap(\"allocation_failed\"); vec->data = data; vec->capacity = next; }}\n\
static inline void fgx_vec_{suffix}_push(fgx_vec_{suffix} *vec, {element} value) {{ fgx_vec_{suffix}_reserve_for_push(vec); vec->data[vec->len++] = value; }}\n\
static inline void fgx_vec_{suffix}_pop(fgx_vec_{suffix} *vec) {{ if (vec->len != 0) --vec->len; }}\n\
static inline fgx_option_{suffix} fgx_vec_{suffix}_pop_value(fgx_vec_{suffix} *vec) {{ if (vec->len == 0) return (fgx_option_{suffix}){{ .has_value = false }}; return (fgx_option_{suffix}){{ .has_value = true, .value = vec->data[--vec->len] }}; }}\n\
static inline bool fgx_vec_{suffix}_pop_has_value(fgx_vec_{suffix} *vec) {{ if (vec->len == 0) return false; --vec->len; return true; }}\n\
static inline {element} fgx_vec_{suffix}_pop_or(fgx_vec_{suffix} *vec, {element} fallback) {{ if (vec->len == 0) return fallback; return vec->data[--vec->len]; }}\n"
    )
}

fn generate_source(project: &Project, header_name: &str, ir: &BackendIr) -> Result<String, String> {
    let program = combined_program(project);
    let mut types = TypeRegistry::default();
    types.collect_program(&program);
    let mut out = String::new();
    out.push_str("/* Generated by fgx build --backend c. */\n");
    out.push_str(&fir_signature_comment(ir));
    out.push_str(&format!("#include \"{header_name}\"\n\n"));

    for decl in program.structs() {
        let ir_struct = ir_struct_for_ast(ir, decl)?;
        if !ir_struct.public {
            out.push_str(&emit_struct_decl_from_ir(ir_struct)?);
            out.push('\n');
            emit_native_named_array_layouts(&types, &decl.name, &mut out)?;
        }
    }

    for decl in program.structs() {
        let ir_struct = ir_struct_for_ast(ir, decl)?;
        if !ir_struct.public {
            let suffix = ident(&decl.name);
            out.push_str(&emit_native_vec_decl(&suffix, &suffix));
        }
    }

    for function in program.functions() {
        ensure_c_lowerable(function)?;
        let ir_function = ir_function_for_ast(ir, function)?;
        if !ir_function.public {
            out.push_str(&format!(
                "static {};\n",
                function_signature_from_ir(ir_function)?
            ));
        }
    }
    if program
        .functions()
        .any(|function| ir_function_for_ast(ir, function).is_ok_and(|function| !function.public))
    {
        out.push('\n');
    }

    let structs = program
        .structs()
        .map(|decl| (decl.name.clone(), decl.clone()))
        .collect::<HashMap<_, _>>();
    let enums = program
        .enums()
        .map(|decl| (decl.name.clone(), decl.clone()))
        .collect::<HashMap<_, _>>();
    let function_returns = program
        .functions()
        .map(|decl| (decl.name.clone(), decl.ret.clone()))
        .collect::<HashMap<_, _>>();
    for function in program.functions() {
        out.push_str(&emit_function(
            function,
            &structs,
            &enums,
            &function_returns,
            ir,
        )?);
        out.push('\n');
    }
    Ok(out)
}

fn emit_enum_decl_from_ir(decl: &IrEnum) -> Result<String, String> {
    let name = ident(&decl.name);
    let tags = decl
        .variants
        .iter()
        .map(|v| format!("{}_{}", name, ident(&v.name)))
        .collect::<Vec<_>>()
        .join(", ");
    // Data-less enums are a plain C enum.
    if !enum_is_tagged_union_ir(decl) {
        return Ok(format!(
            "/* FIR enum {} */\ntypedef enum {{ {tags} }} {name};\n",
            decl.id
        ));
    }
    // Payload-carrying enums are a tagged union: a discriminant plus a union of
    // the payloads (keyed by variant name). Data-less variants take no slot.
    let mut out = format!(
        "/* FIR enum {} */\ntypedef struct {{\n    enum {{ {tags} }} tag;\n    union {{\n",
        decl.id
    );
    for variant in &decl.variants {
        if let Some(ty) = &variant.payload {
            out.push_str(&format!(
                "        {} {};\n",
                c_type_from_ir(ty)?,
                ident(&variant.name)
            ));
        }
    }
    out.push_str(&format!("    }} data;\n}} {name};\n"));
    Ok(out)
}

fn emit_struct_decl_from_ir(decl: &IrStruct) -> Result<String, String> {
    let mut out = String::new();
    out.push_str(&format!("/* FIR struct {} */\n", decl.id));
    out.push_str(&format!("typedef struct {} {{\n", ident(&decl.name)));
    for field in &decl.fields {
        out.push_str(&format!(
            "    {} {};\n",
            c_type_from_ir(&field.ty)?,
            ident(&field.name)
        ));
    }
    out.push_str(&format!("}} {};\n", ident(&decl.name)));
    Ok(out)
}

fn emit_function(
    function: &FunctionDecl,
    structs: &HashMap<String, StructDecl>,
    enums: &HashMap<String, EnumDecl>,
    function_returns: &HashMap<String, Type>,
    ir: &BackendIr,
) -> Result<String, String> {
    ensure_c_lowerable(function)?;
    let mut env = Env::from_params(&function.params, &function.ret, enums, function_returns);
    let ir_function = ir_function_for_ast(ir, function)?;
    let prefix = if ir_function.public {
        String::new()
    } else {
        "static ".to_string()
    };
    let mut out = String::new();
    out.push_str(&format!(
        "{}{} {{\n",
        prefix,
        function_signature_from_ir(ir_function)?
    ));
    try_emit_fir_body(ir_function, &mut env, structs, &mut out).map_err(|reason| {
        format!(
            "C backend could not emit FIR body for function '{}': {reason}",
            function.name
        )
    })?;
    out.push_str("}\n");
    Ok(out)
}

fn try_emit_fir_body(
    function: &IrFunction,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<(), String> {
    let Some(block) = function.blocks.iter().find(|block| block.label == "entry") else {
        return Err("missing entry block".to_string());
    };

    let mut trial_env = env.clone();
    let mut body = String::new();
    body.push_str("    /* FIR body entry */\n");
    let mut cursor = 0;
    match emit_fir_instructions(
        &block.instructions,
        &mut cursor,
        1,
        &mut trial_env,
        structs,
        &mut body,
        &[],
    )? {
        FirCursorStop::End => {}
        FirCursorStop::Terminator(op) => {
            return Err(format!("unexpected top-level FIR terminator '{op}'"));
        }
        FirCursorStop::Unsupported(reason) => return Err(reason),
    }
    if block
        .instructions
        .last()
        .is_none_or(|instruction| instruction.op != "return")
    {
        emit_vec_cleanup(&trial_env, 1, &mut body);
    }
    if function.ret == "void" && !block.instructions.iter().any(|inst| inst.op == "return") {
        body.push_str("    return;\n");
    }
    *env = trial_env;
    out.push_str(&body);
    Ok(())
}

#[derive(Debug, PartialEq, Eq)]
enum FirCursorStop {
    End,
    Terminator(String),
    Unsupported(String),
}

fn emit_fir_instructions(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
    terminators: &[&str],
) -> Result<FirCursorStop, String> {
    while *cursor < instructions.len() {
        let op = instructions[*cursor].op.as_str();
        if terminators.contains(&op) {
            return Ok(FirCursorStop::Terminator(op.to_string()));
        }
        let emitted = match op {
            "if" => emit_fir_if(instructions, cursor, level, env, structs, out)?,
            "for" => emit_fir_for(instructions, cursor, level, env, structs, out)?,
            "while" => emit_fir_while(instructions, cursor, level, env, structs, out)?,
            "match" => emit_fir_match(instructions, cursor, level, env, structs, out)?,
            "let" | "return" | "require" | "assign" | "expr" | "break" | "continue" => {
                let emitted =
                    emit_fir_instruction(&instructions[*cursor], level, env, structs, out)?;
                if emitted {
                    *cursor += 1;
                }
                emitted
            }
            _ => false,
        };
        if !emitted {
            return Ok(FirCursorStop::Unsupported(format!(
                "unsupported or malformed FIR op '{}' at instruction {}",
                instructions[*cursor].op, *cursor
            )));
        }
    }
    Ok(FirCursorStop::End)
}

fn emit_fir_if(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [cond_text, _then_len] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let cond = match parse_expr(cond_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let pad = indent(level);
    out.push_str(&format!(
        "{pad}if ({}) {{\n",
        emit_expr(&cond, env, structs)?
    ));
    *cursor += 1;

    let mut then_env = env.clone();
    let scope_vec_base = env.owned_vecs.len();
    match emit_fir_instructions(
        instructions,
        cursor,
        level + 1,
        &mut then_env,
        structs,
        out,
        &["else", "endif"],
    )? {
        FirCursorStop::Terminator(op) if op == "else" => {
            emit_vec_cleanup_from(&then_env, scope_vec_base, level + 1, out);
            *cursor += 1;
            out.push_str(&format!("{pad}}} else {{\n"));
            let mut else_env = env.clone();
            match emit_fir_instructions(
                instructions,
                cursor,
                level + 1,
                &mut else_env,
                structs,
                out,
                &["endif"],
            )? {
                FirCursorStop::Terminator(op) if op == "endif" => {
                    emit_vec_cleanup_from(&else_env, scope_vec_base, level + 1, out);
                    *cursor += 1;
                    out.push_str(&format!("{pad}}}\n"));
                    Ok(true)
                }
                _ => Ok(false),
            }
        }
        FirCursorStop::Terminator(op) if op == "endif" => {
            emit_vec_cleanup_from(&then_env, scope_vec_base, level + 1, out);
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn emit_fir_for(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [var, start_text, end_text, _body_len] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let start = match parse_expr(start_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let end = match parse_expr(end_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let start = emit_expr(&start, env, structs)?;
    let end = emit_expr(&end, env, structs)?;
    let pad = indent(level);
    out.push_str(&format!(
        "{pad}for (size_t {} = (size_t)({start}); {} < (size_t)({end}); ++{}) {{\n",
        ident(var),
        ident(var),
        ident(var)
    ));
    *cursor += 1;
    let mut loop_env = env.clone();
    loop_env.insert(var, Type::Primitive("usize".to_string()));
    let loop_vec_base = env.owned_vecs.len();
    loop_env.loop_vec_bases.push(loop_vec_base);
    match emit_fir_instructions(
        instructions,
        cursor,
        level + 1,
        &mut loop_env,
        structs,
        out,
        &["endfor"],
    )? {
        FirCursorStop::Terminator(op) if op == "endfor" => {
            emit_vec_cleanup_from(&loop_env, loop_vec_base, level + 1, out);
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn emit_fir_while(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [cond_text, _body_len] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let cond = match parse_expr(cond_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let pad = indent(level);
    out.push_str(&format!(
        "{pad}while ({}) {{\n",
        emit_expr(&cond, env, structs)?
    ));
    *cursor += 1;
    let mut loop_env = env.clone();
    let loop_vec_base = env.owned_vecs.len();
    loop_env.loop_vec_bases.push(loop_vec_base);
    match emit_fir_instructions(
        instructions,
        cursor,
        level + 1,
        &mut loop_env,
        structs,
        out,
        &["endwhile"],
    )? {
        FirCursorStop::Terminator(op) if op == "endwhile" => {
            emit_vec_cleanup_from(&loop_env, loop_vec_base, level + 1, out);
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn emit_fir_match(
    instructions: &[IrInstruction],
    cursor: &mut usize,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let instruction = &instructions[*cursor];
    let [scrutinee_text, _arms] = instruction.args.as_slice() else {
        return Ok(false);
    };
    let scrutinee = match parse_expr(scrutinee_text) {
        Ok(expr) => expr,
        Err(_) => return Ok(false),
    };
    let enum_name = match inferred_c_type(&scrutinee, env, structs) {
        Type::Named(name) => Some(name),
        _ => None,
    };
    let tagged = enum_name
        .as_deref()
        .map(|name| env.is_tagged_union(name))
        .unwrap_or(false);
    let scrut_text = emit_expr(&scrutinee, env, structs)?;
    let pad = indent(level);
    *cursor += 1;

    if tagged {
        let Some(enum_name) = enum_name else {
            return Ok(false);
        };
        let enum_c = ident(&enum_name);
        let inner = indent(level + 1);
        let case_pad = indent(level + 2);
        out.push_str(&format!("{pad}{{\n"));
        out.push_str(&format!("{inner}{enum_c} _fgx_scrut = {scrut_text};\n"));
        out.push_str(&format!("{inner}switch (_fgx_scrut.tag) {{\n"));

        loop {
            let Some(case) = instructions.get(*cursor) else {
                return Ok(false);
            };
            if case.op == "endmatch" {
                *cursor += 1;
                out.push_str(&format!("{inner}}}\n"));
                out.push_str(&format!("{pad}}}\n"));
                return Ok(true);
            }
            if case.op != "case" {
                return Ok(false);
            }
            let [pattern_text] = case.args.as_slice() else {
                return Ok(false);
            };
            let Some(pattern) = parse_fir_pattern(pattern_text) else {
                return Ok(false);
            };
            let scope_vec_base = env.owned_vecs.len();
            let mut arm_env = env.clone();
            match &pattern {
                Pattern::Wildcard => out.push_str(&format!("{case_pad}default: {{\n")),
                Pattern::Variant { path, binding } => {
                    out.push_str(&format!("{case_pad}case {}: {{\n", path.replace("::", "_")));
                    if let Some(bind) = binding {
                        let variant = path.rsplit("::").next().unwrap_or("");
                        if let Some(payload) = env.enums.get(&enum_name).and_then(|decl| {
                            decl.variants
                                .iter()
                                .find(|variant_decl| variant_decl.name == variant)
                                .and_then(|variant_decl| variant_decl.payload.clone())
                        }) {
                            out.push_str(&format!(
                                "{}{} {} = _fgx_scrut.data.{};\n",
                                indent(level + 3),
                                c_type(&payload)?,
                                ident(bind),
                                ident(variant)
                            ));
                            arm_env.insert(bind, payload);
                        }
                    }
                }
            }

            *cursor += 1;
            match emit_fir_instructions(
                instructions,
                cursor,
                level + 3,
                &mut arm_env,
                structs,
                out,
                &["case", "endmatch"],
            )? {
                FirCursorStop::Terminator(op) if op == "case" || op == "endmatch" => {
                    emit_vec_cleanup_from(&arm_env, scope_vec_base, level + 3, out);
                    out.push_str(&format!("{case_pad}}} break;\n"));
                    if op == "endmatch" {
                        *cursor += 1;
                        out.push_str(&format!("{inner}}}\n"));
                        out.push_str(&format!("{pad}}}\n"));
                        return Ok(true);
                    }
                }
                _ => return Ok(false),
            }
        }
    }

    out.push_str(&format!("{pad}switch ({scrut_text}) {{\n"));
    let case_pad = indent(level + 1);
    loop {
        let Some(case) = instructions.get(*cursor) else {
            return Ok(false);
        };
        if case.op == "endmatch" {
            *cursor += 1;
            out.push_str(&format!("{pad}}}\n"));
            return Ok(true);
        }
        if case.op != "case" {
            return Ok(false);
        }
        let [pattern_text] = case.args.as_slice() else {
            return Ok(false);
        };
        let Some(pattern) = parse_fir_pattern(pattern_text) else {
            return Ok(false);
        };
        match &pattern {
            Pattern::Wildcard => out.push_str(&format!("{case_pad}default: {{\n")),
            Pattern::Variant { path, .. } => {
                out.push_str(&format!("{case_pad}case {}: {{\n", path.replace("::", "_")))
            }
        }

        *cursor += 1;
        let scope_vec_base = env.owned_vecs.len();
        let mut arm_env = env.clone();
        match emit_fir_instructions(
            instructions,
            cursor,
            level + 2,
            &mut arm_env,
            structs,
            out,
            &["case", "endmatch"],
        )? {
            FirCursorStop::Terminator(op) if op == "case" || op == "endmatch" => {
                emit_vec_cleanup_from(&arm_env, scope_vec_base, level + 2, out);
                out.push_str(&format!("{case_pad}}} break;\n"));
                if op == "endmatch" {
                    *cursor += 1;
                    out.push_str(&format!("{pad}}}\n"));
                    return Ok(true);
                }
            }
            _ => return Ok(false),
        }
    }
}

fn parse_fir_pattern(text: &str) -> Option<Pattern> {
    let text = text.trim();
    if text == "_" {
        return Some(Pattern::Wildcard);
    }
    let (path, binding) = if let Some(open) = text.find('(') {
        let path = text[..open].trim().to_string();
        let name = text[open + 1..].strip_suffix(')')?.trim().to_string();
        (path, Some(name))
    } else {
        (text.to_string(), None)
    };
    if !path.contains("::") {
        return None;
    }
    Some(Pattern::Variant { path, binding })
}

fn emit_fir_instruction(
    instruction: &IrInstruction,
    level: usize,
    env: &mut Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<bool, String> {
    let pad = indent(level);
    match instruction.op.as_str() {
        "let" => {
            let [name, expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            let ty = instruction
                .ty
                .as_deref()
                .map(Type::parse)
                .unwrap_or_else(|| inferred_c_type(&expr, env, structs));
            let value = match (&expr, native_vec_suffix(&ty), native_option_suffix(&ty)) {
                (Expr::Call { .. }, _, Some(_)) if is_native_option_constructor(&expr) => {
                    emit_native_option_constructor(&expr, &ty, env, structs)?
                }
                (Expr::Call { name, args }, _, Some(suffix))
                    if name == "pop" && args.len() == 1 =>
                {
                    format!(
                        "fgx_vec_{suffix}_pop_value(&{})",
                        emit_expr(&args[0], env, structs)?
                    )
                }
                (Expr::Call { name, args }, Some(suffix), _)
                    if name == "vec_new" && args.is_empty() =>
                {
                    format!("fgx_vec_{suffix}_new()")
                }
                _ => emit_expr(&expr, env, structs)?,
            };
            out.push_str(&format!(
                "{pad}{} {} = {value};\n",
                c_type(&ty)?,
                ident(name)
            ));
            if is_native_vec(&ty) {
                env.owned_vecs.push(name.clone());
            }
            env.insert(name, ty);
        }
        "return" => match instruction.args.as_slice() {
            [] => {
                emit_vec_cleanup(env, level, out);
                out.push_str(&format!("{pad}return;\n"));
            }
            [expr_text] => {
                let expr = match parse_expr(expr_text) {
                    Ok(expr) => expr,
                    Err(_) => return Ok(false),
                };
                let value = match (&expr, native_option_suffix(&env.return_type)) {
                    (Expr::Call { .. }, Some(_)) if is_native_option_constructor(&expr) => {
                        emit_native_option_constructor(&expr, &env.return_type, env, structs)?
                    }
                    (Expr::Call { name, args }, Some(suffix))
                        if name == "pop" && args.len() == 1 =>
                    {
                        format!(
                            "fgx_vec_{suffix}_pop_value(&{})",
                            emit_expr(&args[0], env, structs)?
                        )
                    }
                    _ => emit_expr(&expr, env, structs)?,
                };
                if env.owned_vecs.is_empty() {
                    out.push_str(&format!("{pad}return {value};\n"));
                } else {
                    let temp = env.next_return_temp();
                    out.push_str(&format!(
                        "{pad}{} {temp} = {value};\n",
                        c_type(&env.return_type)?
                    ));
                    emit_vec_cleanup(env, level, out);
                    out.push_str(&format!("{pad}return {temp};\n"));
                }
            }
            _ => return Ok(false),
        },
        "require" => {
            let [expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            out.push_str(&format!(
                "{pad}if (!({})) fgx_trap(\"require_failed\");\n",
                emit_expr(&expr, env, structs)?
            ));
        }
        "assign" => {
            let [target_text, expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let target = match parse_expr(target_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            emit_assignment(&target, &expr, level, env, structs, out)?;
        }
        "expr" => {
            let [expr_text] = instruction.args.as_slice() else {
                return Ok(false);
            };
            let expr = match parse_expr(expr_text) {
                Ok(expr) => expr,
                Err(_) => return Ok(false),
            };
            out.push_str(&format!("{pad}{};\n", emit_expr(&expr, env, structs)?));
        }
        "break" => {
            emit_loop_vec_cleanup(env, level, out)?;
            out.push_str(&format!("{pad}break;\n"));
        }
        "continue" => {
            emit_loop_vec_cleanup(env, level, out)?;
            out.push_str(&format!("{pad}continue;\n"));
        }
        _ => return Ok(false),
    }
    Ok(true)
}

fn emit_assignment(
    target: &Expr,
    expr: &Expr,
    level: usize,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
    out: &mut String,
) -> Result<(), String> {
    let pad = indent(level);
    let value = emit_expr(expr, env, structs)?;
    match target {
        Expr::Index { base, index } => {
            let base_text = emit_expr(base, env, structs)?;
            let index_text = emit_expr(index, env, structs)?;
            out.push_str(&format!(
                "{pad}{base_text}.data[fgx_bounds_index((size_t)({index_text}), {base_text}.len)] = {value};\n"
            ));
        }
        _ => out.push_str(&format!(
            "{pad}{} = {value};\n",
            emit_expr(target, env, structs)?
        )),
    }
    Ok(())
}

fn emit_expr(
    expr: &Expr,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    match expr {
        Expr::Lambda { .. } => Err("C backend cannot lower closures yet".to_string()),
        Expr::SliceRange { .. } => {
            Err("C backend cannot lower slice-range expressions yet".to_string())
        }
        Expr::Int(value) => Ok(value.to_string()),
        Expr::Float(value) => Ok(c_float(*value)),
        Expr::Bool(value) => Ok(value.to_string()),
        Expr::String(value) => Ok(c_string(value)),
        Expr::TraitConst { .. } => {
            Err("C backend received an unresolved trait constant".to_string())
        }
        Expr::Var(name) if name.contains("::") => {
            // A data-less enum variant value. In a plain enum it is the
            // `Enum_Variant` constant; in a tagged union it is a struct literal
            // carrying only the discriminant.
            let (enum_name, _) = name.split_once("::").unwrap();
            let tag = name.replace("::", "_");
            if env.is_tagged_union(enum_name) {
                Ok(format!("({}){{ .tag = {tag} }}", ident(enum_name)))
            } else {
                Ok(tag)
            }
        }
        Expr::Call { name, args } if name.contains("::") => {
            // A payload-carrying variant constructor, `Shape::Circle(r)`, lowers
            // to a tagged-union literal `(Shape){ .tag = Shape_Circle, .data.Circle = (r) }`.
            let (enum_name, variant) = name.split_once("::").unwrap();
            let tag = name.replace("::", "_");
            match args.first() {
                Some(arg) => {
                    let value = emit_expr(arg, env, structs)?;
                    Ok(format!(
                        "({}){{ .tag = {tag}, .data.{} = ({value}) }}",
                        ident(enum_name),
                        ident(variant)
                    ))
                }
                None if env.is_tagged_union(enum_name) => {
                    Ok(format!("({}){{ .tag = {tag} }}", ident(enum_name)))
                }
                None => Ok(tag),
            }
        }
        Expr::Var(name) => {
            let _known = env.values.contains_key(name);
            Ok(ident(name))
        }
        Expr::Unary { op, expr } => Ok(format!("({op}{})", emit_expr(expr, env, structs)?)),
        Expr::Binary { op, left, right }
            if matches!(op.as_str(), "==" | "!=")
                && inferred_c_type(left, env, structs) == Type::Primitive("str".to_string())
                && inferred_c_type(right, env, structs) == Type::Primitive("str".to_string()) =>
        {
            let equality = format!(
                "fgx_str_eq({}, {})",
                emit_expr(left, env, structs)?,
                emit_expr(right, env, structs)?
            );
            if op == "==" {
                Ok(equality)
            } else {
                Ok(format!("(!{equality})"))
            }
        }
        Expr::Binary { op, left, right } => Ok(format!(
            "({} {} {})",
            emit_expr(left, env, structs)?,
            op,
            emit_expr(right, env, structs)?
        )),
        Expr::Call { name, args } => {
            if is_cpu_feature_probe(name) || name == "aligned" {
                return Ok("false".to_string());
            }
            if matches!(name.as_str(), "is_some" | "is_none" | "unwrap_or") {
                if let Some(Expr::Call {
                    name: pop_name,
                    args: pop_args,
                }) = args.first()
                {
                    if pop_name == "pop" && pop_args.len() == 1 {
                        let vec = &pop_args[0];
                        let suffix = native_vec_suffix(&inferred_c_type(vec, env, structs))
                            .ok_or_else(|| {
                                "C backend value pop requires a supported local native Vec"
                                    .to_string()
                            })?;
                        let vec = emit_expr(vec, env, structs)?;
                        match (name.as_str(), args.as_slice()) {
                            ("is_some", [_]) => {
                                return Ok(format!("fgx_vec_{suffix}_pop_has_value(&{vec})"));
                            }
                            ("is_none", [_]) => {
                                return Ok(format!("(!fgx_vec_{suffix}_pop_has_value(&{vec}))"));
                            }
                            ("unwrap_or", [_, fallback]) => {
                                return Ok(format!(
                                    "fgx_vec_{suffix}_pop_or(&{vec}, {})",
                                    emit_expr(fallback, env, structs)?
                                ));
                            }
                            _ => {}
                        }
                    }
                }
                if let Some(option) = args.first() {
                    if native_option_suffix(&inferred_c_type(option, env, structs)).is_some() {
                        let option = emit_expr(option, env, structs)?;
                        match (name.as_str(), args.as_slice()) {
                            ("is_some", [_]) => return Ok(format!("({option}).has_value")),
                            ("is_none", [_]) => {
                                return Ok(format!("(!({option}).has_value)"));
                            }
                            ("unwrap_or", [_, fallback]) => {
                                return Ok(format!(
                                    "(({option}).has_value ? ({option}).value : {})",
                                    emit_expr(fallback, env, structs)?
                                ));
                            }
                            _ => {}
                        }
                    }
                }
            }
            if matches!(
                name.as_str(),
                "Some"
                    | "None"
                    | "Ok"
                    | "Err"
                    | "is_some"
                    | "is_none"
                    | "is_ok"
                    | "is_err"
                    | "unwrap_or"
            ) {
                return Err(format!(
                    "C backend does not lower interpreter-only intrinsic '{name}' yet"
                ));
            }
            let vec_suffix = args
                .first()
                .and_then(|arg| native_vec_suffix(&inferred_c_type(arg, env, structs)));
            let values = args
                .iter()
                .map(|arg| emit_expr(arg, env, structs))
                .collect::<Result<Vec<_>, _>>()?;
            match (name.as_str(), values.as_slice()) {
                ("vec_new", []) => {
                    return Err(
                        "C backend vec_new requires an annotated supported local Vec".to_string(),
                    );
                }
                ("push", [vec, value]) => {
                    let suffix = vec_suffix.ok_or_else(|| {
                        "C backend push requires a supported local native Vec".to_string()
                    })?;
                    return Ok(format!("fgx_vec_{suffix}_push(&{vec}, {value})"));
                }
                ("pop", [vec]) => {
                    let suffix = vec_suffix.ok_or_else(|| {
                        "C backend pop requires a supported local native Vec".to_string()
                    })?;
                    return Ok(format!("fgx_vec_{suffix}_pop(&{vec})"));
                }
                ("str_len", [value]) => return Ok(format!("fgx_str_len({value})")),
                ("str_contains", [text, needle]) => {
                    return Ok(format!("fgx_str_contains({text}, {needle})"));
                }
                ("vec_new" | "push" | "pop" | "str_len" | "str_contains", _) => {
                    return Err(format!("C backend received invalid arity for '{name}'"));
                }
                _ => {}
            }
            if let Some(decl) = structs.get(name) {
                let fields = decl
                    .fields
                    .iter()
                    .zip(values.iter())
                    .map(|(field, value)| format!(".{} = {value}", ident(&field.name)))
                    .collect::<Vec<_>>()
                    .join(", ");
                return Ok(format!("(({}){{ {fields} }})", ident(name)));
            }
            Ok(format!("{}({})", ident(name), values.join(", ")))
        }
        Expr::Cast { ty, expr } => Ok(format!(
            "(({})({}))",
            c_type(ty)?,
            emit_expr(expr, env, structs)?
        )),
        Expr::Field { base, field }
            if field == "len"
                && inferred_c_type(base, env, structs) == Type::Primitive("str".to_string()) =>
        {
            Ok(format!("fgx_str_len({})", emit_expr(base, env, structs)?))
        }
        Expr::Field { base, field } => Ok(format!(
            "{}.{}",
            emit_expr(base, env, structs)?,
            ident(field)
        )),
        Expr::Index { base, index } => {
            let base_text = emit_expr(base, env, structs)?;
            let index_text = emit_expr(index, env, structs)?;
            let len = match inferred_c_type(base, env, structs) {
                Type::Array { len, .. } => len.to_string(),
                _ => format!("{base_text}.len"),
            };
            Ok(format!(
                "{base_text}.data[fgx_bounds_index((size_t)({index_text}), {len})]"
            ))
        }
    }
}

fn fir_signature_comment(ir: &BackendIr) -> String {
    format!(
        "/* FIR signatures: forgentex.backend_ir.v1 package={} version={} */\n",
        ir.package, ir.version
    )
}

fn ir_function_for_ast<'a>(
    ir: &'a BackendIr,
    function: &FunctionDecl,
) -> Result<&'a IrFunction, String> {
    ir.modules
        .iter()
        .flat_map(|module| module.functions.iter())
        .find(|candidate| candidate.id == function.id && candidate.name == function.name)
        .ok_or_else(|| format!("FIR function missing for '{}'", function.name))
}

fn ir_enum_for_ast<'a>(ir: &'a BackendIr, decl: &EnumDecl) -> Result<&'a IrEnum, String> {
    ir.modules
        .iter()
        .flat_map(|module| module.enums.iter())
        .find(|candidate| candidate.id == decl.id && candidate.name == decl.name)
        .ok_or_else(|| format!("FIR enum missing for '{}'", decl.name))
}

fn ir_struct_for_ast<'a>(ir: &'a BackendIr, decl: &StructDecl) -> Result<&'a IrStruct, String> {
    ir.modules
        .iter()
        .flat_map(|module| module.structs.iter())
        .find(|candidate| candidate.id == decl.id && candidate.name == decl.name)
        .ok_or_else(|| format!("FIR struct missing for '{}'", decl.name))
}

fn function_signature_from_ir(function: &IrFunction) -> Result<String, String> {
    let params = if function.params.is_empty() {
        "void".to_string()
    } else {
        function
            .params
            .iter()
            .map(|param| {
                Ok(format!(
                    "{} {}",
                    c_type_from_ir(&param.ty)?,
                    ident(&param.name)
                ))
            })
            .collect::<Result<Vec<String>, String>>()?
            .join(", ")
    };
    Ok(format!(
        "{} {}({params})",
        c_type_from_ir(&function.ret)?,
        ident(&function.name)
    ))
}

fn c_type_from_ir(ty: &str) -> Result<String, String> {
    c_type(&Type::parse(ty))
}

fn c_type(ty: &Type) -> Result<String, String> {
    match ty {
        Type::Bool => Ok("bool".to_string()),
        Type::Primitive(name) => match name.as_str() {
            "i8" => Ok("int8_t".to_string()),
            "i16" => Ok("int16_t".to_string()),
            "i32" => Ok("int32_t".to_string()),
            "i64" => Ok("int64_t".to_string()),
            "isize" => Ok("ptrdiff_t".to_string()),
            "u8" => Ok("uint8_t".to_string()),
            "u16" => Ok("uint16_t".to_string()),
            "u32" => Ok("uint32_t".to_string()),
            "u64" => Ok("uint64_t".to_string()),
            "usize" => Ok("size_t".to_string()),
            "f32" => Ok("float".to_string()),
            "f64" => Ok("double".to_string()),
            "str" => Ok("const char *".to_string()),
            "$int" => Ok("int64_t".to_string()),
            "$float" => Ok("double".to_string()),
            other => Err(format!("C backend does not know primitive type '{other}'")),
        },
        Type::Named(name) => Ok(ident(name)),
        ty @ Type::Generic { name, .. } if is_native_vec(ty) => {
            Ok(format!("fgx_vec_{}", native_vec_suffix(ty).unwrap()))
        }
        ty @ Type::Generic { name, .. } if native_option_suffix(ty).is_some() => {
            Ok(format!("fgx_option_{}", native_option_suffix(ty).unwrap()))
        }
        ty @ Type::Generic { name, .. } if name == "Fn" && is_native_function_type(ty) => {
            function_type_name(ty)
        }
        Type::Generic { name, .. } => {
            Err(format!("C backend does not lower generic type '{}'", name))
        }
        Type::Array { elem, len } => Ok(array_type_name(elem, *len)?),
        Type::Slice { mutable, elem } => Ok(slice_type_name(elem, *mutable)?),
        Type::Pointer { mutable, elem } => {
            if *mutable {
                Ok(format!("{} *", c_type(elem)?))
            } else {
                Ok(format!("const {} *", c_type(elem)?))
            }
        }
        Type::Void => Ok("void".to_string()),
        Type::Unknown => Ok("void *".to_string()),
    }
}

fn ensure_c_lowerable(function: &FunctionDecl) -> Result<(), String> {
    if function.unsafe_fn || function.has_asm() {
        return Err(format!(
            "C backend cannot lower unsafe or assembly function '{}'",
            function.name
        ));
    }
    for effect in &function.effects {
        if is_runtime_only_effect(effect)
            && !(effect == "alloc" && function_has_native_vec(function))
        {
            return Err(format!(
                "C backend cannot lower runtime effect '{}' in function '{}'",
                effect, function.name
            ));
        }
    }
    Ok(())
}

fn combined_program(project: &Project) -> Program {
    let mut items = Vec::new();
    for module in &project.modules {
        items.extend(module.program.items.clone());
    }
    Program { items }
}

fn function_has_native_vec(function: &FunctionDecl) -> bool {
    stmts_have_native_vec(&function.body)
}

fn stmts_have_native_vec(body: &[crate::ast::Stmt]) -> bool {
    body.iter().any(|stmt| match stmt {
        crate::ast::Stmt::Let {
            ty: Some(ty),
            expr: Expr::Call { name, args },
            ..
        } => is_native_vec(ty) && name == "vec_new" && args.is_empty(),
        crate::ast::Stmt::If {
            then_body,
            else_body,
            ..
        } => stmts_have_native_vec(then_body) || stmts_have_native_vec(else_body),
        crate::ast::Stmt::For { body, .. } | crate::ast::Stmt::While { body, .. } => {
            stmts_have_native_vec(body)
        }
        crate::ast::Stmt::Match { arms, .. } => {
            arms.iter().any(|arm| stmts_have_native_vec(&arm.body))
        }
        _ => false,
    })
}

#[derive(Clone)]
struct Env {
    values: HashMap<String, Type>,
    // Enum declarations, so variant construction and `match` know whether an
    // enum is a tagged union (any payload variant) and a variant's payload type.
    enums: HashMap<String, EnumDecl>,
    function_returns: HashMap<String, Type>,
    return_type: Type,
    owned_vecs: Vec<String>,
    loop_vec_bases: Vec<usize>,
    return_temps: usize,
}

impl Env {
    fn from_params(
        params: &[Param],
        return_type: &Type,
        enums: &HashMap<String, EnumDecl>,
        function_returns: &HashMap<String, Type>,
    ) -> Self {
        let values = params
            .iter()
            .map(|param| (param.name.clone(), param.ty.clone()))
            .collect();
        Self {
            values,
            enums: enums.clone(),
            function_returns: function_returns.clone(),
            return_type: return_type.clone(),
            owned_vecs: Vec::new(),
            loop_vec_bases: Vec::new(),
            return_temps: 0,
        }
    }

    fn insert(&mut self, name: &str, ty: Type) {
        self.values.insert(name.to_string(), ty);
    }

    fn next_return_temp(&mut self) -> String {
        let name = format!("_fgx_return_{}", self.return_temps);
        self.return_temps += 1;
        name
    }

    /// An enum is a tagged union iff some variant carries a payload.
    fn is_tagged_union(&self, enum_name: &str) -> bool {
        self.enums
            .get(enum_name)
            .map(enum_is_tagged_union)
            .unwrap_or(false)
    }
}

fn enum_is_tagged_union(decl: &EnumDecl) -> bool {
    decl.variants.iter().any(|v| v.payload.is_some())
}

fn enum_is_tagged_union_ir(decl: &IrEnum) -> bool {
    decl.variants
        .iter()
        .any(|variant| variant.payload.is_some())
}

fn inferred_c_type(expr: &Expr, env: &Env, structs: &HashMap<String, StructDecl>) -> Type {
    match expr {
        Expr::Lambda { .. } => Type::Unknown,
        Expr::Int(_) => Type::Primitive("i64".to_string()),
        Expr::Float(_) => Type::Primitive("f64".to_string()),
        Expr::Bool(_) => Type::Bool,
        Expr::String(_) => Type::Primitive("str".to_string()),
        Expr::TraitConst { .. } => Type::Unknown,
        Expr::Var(name) if name.contains("::") => {
            Type::Named(name.split("::").next().unwrap_or(name).to_string())
        }
        Expr::Var(name) => env.values.get(name).cloned().unwrap_or(Type::Unknown),
        Expr::Call { name, .. } if name.contains("::") => {
            Type::Named(name.split("::").next().unwrap_or(name).to_string())
        }
        Expr::Call { name, .. } if structs.contains_key(name) => Type::Named(name.clone()),
        Expr::Call { name, .. } => env
            .function_returns
            .get(name)
            .cloned()
            .unwrap_or(Type::Unknown),
        Expr::Cast { ty, .. } => ty.clone(),
        Expr::Field { base, field } if field == "len" => {
            let base_ty = inferred_c_type(base, env, structs);
            if matches!(base_ty, Type::Slice { .. } | Type::Array { .. })
                || is_native_vec(&base_ty)
                || base_ty == Type::Primitive("str".to_string())
            {
                Type::Primitive("usize".to_string())
            } else {
                Type::Unknown
            }
        }
        Expr::Index { base, .. } => inferred_c_type(base, env, structs)
            .element_type()
            .unwrap_or(Type::Unknown),
        Expr::SliceRange { base, .. } => match inferred_c_type(base, env, structs) {
            Type::Slice { mutable, elem } => Type::Slice { mutable, elem },
            Type::Array { elem, .. } => Type::Slice {
                mutable: false,
                elem,
            },
            _ => Type::Unknown,
        },
        Expr::Unary { expr, .. } => inferred_c_type(expr, env, structs),
        Expr::Binary { left, right, .. } => {
            let left = inferred_c_type(left, env, structs);
            let right = inferred_c_type(right, env, structs);
            if left == right {
                left
            } else if left.is_float() || right.is_float() {
                Type::Primitive("f64".to_string())
            } else {
                Type::Primitive("i64".to_string())
            }
        }
        Expr::Field { .. } => Type::Unknown,
    }
}

fn native_vec_suffix(ty: &Type) -> Option<String> {
    let Type::Generic { name, args } = ty else {
        return None;
    };
    let [element] = args.as_slice() else {
        return None;
    };
    if name != "Vec" {
        return None;
    }
    match element {
        Type::Bool => Some("bool".to_string()),
        Type::Primitive(element) => match element.as_str() {
            "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize"
            | "f32" | "f64" | "str" => Some(element.clone()),
            _ => None,
        },
        Type::Named(element) => Some(ident(element)),
        Type::Slice {
            mutable: false,
            elem,
        } if native_vec_slice_element(elem) => Some(format!("slice_{}", type_suffix(elem).ok()?)),
        element @ Type::Array { elem, len } if is_native_vec_array_element(element) => {
            Some(format!("array_{}_{}", type_suffix(elem).ok()?, len))
        }
        _ => None,
    }
}

fn native_option_suffix(ty: &Type) -> Option<String> {
    let Type::Generic { name, args } = ty else {
        return None;
    };
    if name != "Option" || args.len() != 1 {
        return None;
    }
    native_vec_suffix(&Type::Generic {
        name: "Vec".to_string(),
        args: args.clone(),
    })
}

fn is_native_option_constructor(expr: &Expr) -> bool {
    matches!(expr, Expr::Call { name, args } if (name == "Some" && args.len() == 1) || (name == "None" && args.is_empty()))
}

fn emit_native_option_constructor(
    expr: &Expr,
    ty: &Type,
    env: &Env,
    structs: &HashMap<String, StructDecl>,
) -> Result<String, String> {
    let suffix = native_option_suffix(ty).ok_or_else(|| {
        "C backend Option constructor requires a supported value type".to_string()
    })?;
    match expr {
        Expr::Call { name, args } if name == "Some" && args.len() == 1 => Ok(format!(
            "(fgx_option_{suffix}){{ .has_value = true, .value = {} }}",
            emit_expr(&args[0], env, structs)?
        )),
        Expr::Call { name, args } if name == "None" && args.is_empty() => {
            Ok(format!("(fgx_option_{suffix}){{ .has_value = false }}"))
        }
        _ => Err("C backend received an invalid Option constructor".to_string()),
    }
}

fn native_vec_slice_element(ty: &Type) -> bool {
    match ty {
        Type::Bool => true,
        Type::Primitive(element) => matches!(
            element.as_str(),
            "i8" | "i16"
                | "i32"
                | "i64"
                | "isize"
                | "u8"
                | "u16"
                | "u32"
                | "u64"
                | "usize"
                | "f32"
                | "f64"
        ),
        _ => false,
    }
}

fn is_native_vec(ty: &Type) -> bool {
    native_vec_suffix(ty).is_some()
}

fn emit_vec_cleanup(env: &Env, level: usize, out: &mut String) {
    emit_vec_cleanup_from(env, 0, level, out);
}

fn emit_vec_cleanup_from(env: &Env, base: usize, level: usize, out: &mut String) {
    let pad = indent(level);
    for name in env.owned_vecs[base..].iter().rev() {
        let suffix = env
            .values
            .get(name)
            .and_then(native_vec_suffix)
            .expect("owned native Vec must retain its concrete element layout");
        out.push_str(&format!("{pad}fgx_vec_{suffix}_free(&{});\n", ident(name)));
    }
}

fn emit_loop_vec_cleanup(env: &Env, level: usize, out: &mut String) -> Result<(), String> {
    let base = env
        .loop_vec_bases
        .last()
        .copied()
        .ok_or_else(|| "C backend received loop control outside a loop".to_string())?;
    emit_vec_cleanup_from(env, base, level, out);
    Ok(())
}

fn is_runtime_only_effect(effect: &str) -> bool {
    effect == "alloc"
        || effect.starts_with("alloc.")
        || effect.starts_with("io.")
        || effect.starts_with("fs.")
        || effect.starts_with("network.")
        || effect.starts_with("crypto.")
        || effect.starts_with("ledger.")
        || effect.starts_with("agent.")
        || effect.starts_with("concurrency.")
        || effect == "serialize"
        || effect == "stream"
}

fn c_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

#[derive(Default)]
struct TypeRegistry {
    slices: BTreeMap<(bool, String), Type>,
    arrays: BTreeMap<(String, usize), Type>,
    functions: BTreeMap<String, Type>,
}

impl TypeRegistry {
    fn collect_program(&mut self, program: &Program) {
        for item in &program.items {
            match item {
                Item::Struct(decl) => {
                    for field in &decl.fields {
                        self.collect_type(&field.ty);
                    }
                }
                Item::Function(function) => {
                    self.collect_type(&function.ret);
                    for param in &function.params {
                        self.collect_type(&param.ty);
                    }
                    self.collect_stmt_types(&function.body);
                }
                Item::Enum(decl) => {
                    for variant in &decl.variants {
                        if let Some(payload) = &variant.payload {
                            self.collect_type(payload);
                        }
                    }
                }
                // Capsules are review-only foreign code; shares are metadata.
                Item::Trait(_)
                | Item::TraitImpl(_)
                | Item::Test(_)
                | Item::Capsule(_)
                | Item::Share(_)
                | Item::Pipeline(_) => {}
            }
        }
    }

    fn collect_type(&mut self, ty: &Type) {
        match ty {
            Type::Generic { name, .. } if name == "Fn" && is_native_function_type(ty) => {
                // Effects are erased from the machine ABI. Key by the emitted
                // name so pure and effectful contracts with the same scalar
                // signature share exactly one C typedef.
                if let Ok(name) = function_type_name(ty) {
                    self.functions.insert(name, ty.clone());
                }
            }
            Type::Slice { mutable, elem } => {
                self.collect_type(elem);
                self.slices
                    .insert((*mutable, elem.to_agent()), elem.as_ref().clone());
            }
            Type::Array { elem, len } => {
                self.collect_type(elem);
                self.arrays
                    .insert((elem.to_agent(), *len), elem.as_ref().clone());
            }
            Type::Pointer { elem, .. } => self.collect_type(elem),
            Type::Generic { args, .. } => {
                for arg in args {
                    self.collect_type(arg);
                }
            }
            _ => {}
        }
    }

    fn collect_stmt_types(&mut self, body: &[crate::ast::Stmt]) {
        for stmt in body {
            match stmt {
                crate::ast::Stmt::Let { ty: Some(ty), .. } => self.collect_type(ty),
                crate::ast::Stmt::If {
                    then_body,
                    else_body,
                    ..
                } => {
                    self.collect_stmt_types(then_body);
                    self.collect_stmt_types(else_body);
                }
                crate::ast::Stmt::For { body, .. } | crate::ast::Stmt::While { body, .. } => {
                    self.collect_stmt_types(body)
                }
                crate::ast::Stmt::Match { arms, .. } => {
                    for arm in arms {
                        self.collect_stmt_types(&arm.body);
                    }
                }
                crate::ast::Stmt::Let { ty: None, .. }
                | crate::ast::Stmt::Return(_)
                | crate::ast::Stmt::Require(_)
                | crate::ast::Stmt::Break
                | crate::ast::Stmt::Continue
                | crate::ast::Stmt::Assign { .. }
                | crate::ast::Stmt::Expr(_)
                | crate::ast::Stmt::Asm(_) => {}
            }
        }
    }

    fn typedefs(&self) -> Vec<String> {
        let mut out = Vec::new();
        for ty in self.functions.values() {
            if let Some((params, ret, _)) = ty.function_parts() {
                let params = if params.is_empty() {
                    "void".to_string()
                } else {
                    params
                        .iter()
                        .map(c_type)
                        .collect::<Result<Vec<_>, _>>()
                        .unwrap_or_default()
                        .join(", ")
                };
                if let (Ok(name), Ok(ret)) = (function_type_name(ty), c_type(ret)) {
                    out.push(format!("typedef {ret} (*{name})({params});"));
                }
            }
        }
        let mut emitted_wrappers = BTreeSet::new();
        for ((_, len), elem) in &self.arrays {
            let array = Type::Array {
                elem: Box::new(elem.clone()),
                len: *len,
            };
            if array_named_leaf(&array).is_none() {
                emit_wrapper_typedef(&array, &mut emitted_wrappers, &mut out);
            }
        }
        for ((mutable, _), elem) in &self.slices {
            emit_wrapper_typedef(
                &Type::Slice {
                    mutable: *mutable,
                    elem: Box::new(elem.clone()),
                },
                &mut emitted_wrappers,
                &mut out,
            );
        }
        out
    }

    fn is_empty(&self) -> bool {
        self.slices.is_empty() && self.arrays.is_empty() && self.functions.is_empty()
    }
}

fn array_named_leaf(ty: &Type) -> Option<&str> {
    match ty {
        Type::Array { elem, .. } => match elem.as_ref() {
            Type::Named(name) => Some(name),
            nested @ Type::Array { .. } => array_named_leaf(nested),
            _ => None,
        },
        _ => None,
    }
}

fn emit_native_named_array_layouts(
    types: &TypeRegistry,
    named_leaf: &str,
    out: &mut String,
) -> Result<(), String> {
    let arrays = types
        .arrays
        .iter()
        .filter_map(|((_, len), elem)| {
            let array = Type::Array {
                elem: Box::new(elem.clone()),
                len: *len,
            };
            (array_named_leaf(&array) == Some(named_leaf) && is_native_vec_array_element(&array))
                .then_some(array)
        })
        .collect::<Vec<_>>();
    let mut typedefs = Vec::new();
    let mut emitted_wrappers = BTreeSet::new();
    for array in &arrays {
        emit_wrapper_typedef(array, &mut emitted_wrappers, &mut typedefs);
    }
    for typedef in typedefs {
        out.push_str(&typedef);
        out.push('\n');
    }
    for array in arrays {
        let Type::Array { elem, len } = array else {
            unreachable!();
        };
        let suffix = format!("array_{}_{}", type_suffix(&elem)?, len);
        let element = array_type_name(&elem, len)?;
        out.push_str(&emit_native_vec_decl(&suffix, &element));
    }
    Ok(())
}

fn emit_wrapper_typedef(ty: &Type, emitted: &mut BTreeSet<String>, out: &mut Vec<String>) {
    let (name, elem) = match ty {
        Type::Array { elem, len } => (array_type_name(elem, *len), elem.as_ref()),
        Type::Slice { mutable, elem } => (slice_type_name(elem, *mutable), elem.as_ref()),
        _ => return,
    };
    let Ok(name) = name else { return };
    if emitted.contains(&name) {
        return;
    }
    if matches!(elem, Type::Array { .. } | Type::Slice { .. }) {
        emit_wrapper_typedef(elem, emitted, out);
    }
    let Ok(c_elem) = c_type(elem) else {
        return;
    };
    match ty {
        Type::Array { len, .. } => out.push(format!(
            "typedef struct {name} {{ {c_elem} data[{len}]; }} {name};"
        )),
        Type::Slice { mutable, .. } => {
            let qualifier = if *mutable { "" } else { "const " };
            out.push(format!(
                "typedef struct {name} {{ {qualifier}{c_elem} *data; size_t len; }} {name};"
            ));
        }
        _ => unreachable!(),
    }
    emitted.insert(name);
}

fn function_type_name(ty: &Type) -> Result<String, String> {
    if !is_native_function_type(ty) {
        return Err("C backend received an unsupported function type".to_string());
    }
    let (params, ret, _) = ty
        .function_parts()
        .ok_or_else(|| "C backend received a malformed function type".to_string())?;
    let mut parts = params
        .iter()
        .map(type_suffix)
        .collect::<Result<Vec<_>, _>>()?;
    parts.push(type_suffix(ret)?);
    Ok(format!("fgx_fn_{}", parts.join("_")))
}

fn slice_type_name(elem: &Type, mutable: bool) -> Result<String, String> {
    let prefix = if mutable {
        "fgx_slice"
    } else {
        "fgx_const_slice"
    };
    Ok(format!("{prefix}_{}", type_suffix(elem)?))
}

fn array_type_name(elem: &Type, len: usize) -> Result<String, String> {
    Ok(format!("fgx_array_{}_{}", type_suffix(elem)?, len))
}

fn type_suffix(ty: &Type) -> Result<String, String> {
    match ty {
        Type::Bool => Ok("bool".to_string()),
        Type::Primitive(name) | Type::Named(name) => Ok(ident(name)),
        Type::Pointer { mutable, elem } => {
            let mutability = if *mutable { "mut" } else { "const" };
            Ok(format!("ptr_{mutability}_{}", type_suffix(elem)?))
        }
        Type::Slice { mutable, elem } => {
            let mutability = if *mutable { "mut" } else { "const" };
            Ok(format!("slice_{mutability}_{}", type_suffix(elem)?))
        }
        Type::Array { elem, len } => Ok(format!("array_{}_{}", type_suffix(elem)?, len)),
        Type::Generic { name, args } => {
            let args = args
                .iter()
                .map(type_suffix)
                .collect::<Result<Vec<_>, _>>()?
                .join("_");
            Ok(format!("{}_{}", ident(name), args))
        }
        Type::Void => Ok("void".to_string()),
        Type::Unknown => Ok("unknown".to_string()),
    }
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

fn ident(name: &str) -> String {
    let mut out = String::new();
    for (idx, ch) in name.chars().enumerate() {
        if ch == '_' || ch.is_ascii_alphanumeric() {
            if idx == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        "_".to_string()
    } else {
        out
    }
}

fn package_ident(name: &str) -> String {
    ident(&name.replace('-', "_"))
}

fn header_guard(header_name: &str) -> String {
    format!("{}_INCLUDED", ident(header_name).to_ascii_uppercase())
}

fn c_float(value: f64) -> String {
    let mut text = value.to_string();
    if !text.contains('.') {
        text.push_str(".0");
    }
    text
}
